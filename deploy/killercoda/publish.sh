#!/usr/bin/env bash
# Copy an export (study-lab export --target killercoda --evidence ...) into a clone of the mirror and commit it.
# Usage: publish.sh <export dir> <mirror clone>
# Never deletes anything because evidence is missing: an export with no scenario refuses to touch the mirror, and
# files are only added or updated (a scenario that was not re-proven keeps its files; structure.json decides what is listed).
set -euo pipefail
BUILD=${1:?export dir}; MIRROR=${2:?mirror clone}
n=$(find "$BUILD" -name index.json -not -path "$BUILD/probe/*" | wc -l)
if [ "$n" -eq 0 ]; then echo "the export has no scenario with valid evidence: refusing to touch the mirror" >&2; exit 3; fi
# the hand-written files of the mirror (README, CONTRIBUTING, CODEOWNERS, .github, .gitattributes) are never generated
rsync -a --exclude .git --exclude .github --exclude README.md --exclude CONTRIBUTING.md --exclude CODEOWNERS \
  --exclude .gitattributes "$BUILD"/ "$MIRROR"/
git -C "$MIRROR" add -A
if git -C "$MIRROR" diff --cached --quiet; then echo "mirror already up to date: no commit"; exit 0; fi
git -C "$MIRROR" -c user.name="study-cybercirujas bot" -c user.email="noreply@users.noreply.github.com" commit -q -s \
  -m "export: study@${STUDY_SHA:-unknown}" -m "Generated by study-lab export --target killercoda; evidence: ${EVIDENCE_URL:-none}"
echo "committed $(git -C "$MIRROR" rev-parse --short HEAD) with $n scenario(s)"
