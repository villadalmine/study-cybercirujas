# FAULT 3 — audit records are not attributable
# -----------------------------------------------------------------------------
#
#   Diagnosis
#     $ tail -n 1 var/log/mcp/audit.jsonl
#     {"ts":"2026-09-17T10:07:02.551Z","event":"tool.call","server":"records-audit",
#      "transport":"stdio","tool":"query_records","outcome":"ok","rows":3,"duration_ms":1}
#
#     It records what happened. It does not record who asked, in which
#     session, or under which JSON-RPC request id — so this line cannot be
#     joined to the client's transcript, to the notifications/message stream,
#     or to anything upstream. audit() even receives request_id as an
#     argument and drops it on the floor.
#
#   Fix — server/mcp_audit_server.py, function audit():
#
#       def audit(event: str, request_id=None, **fields) -> None:
#           record = {
#               "ts": _ts(),
#               "event": event,
#               "server": SERVER_INFO["name"],
#               "transport": "stdio",
#               "session_id": STATE["session_id"],     # which session
#               "principal": STATE["principal"],       # who is calling
#               "request_id": request_id,              # which JSON-RPC request
#           }
#           record.update(fields)
#           _audit_write(json.dumps(record, separators=(",", ":")) + "\n")
#
#     The correlation context is fixed in the record builder, not at the call
#     sites, so a new call site cannot forget it. Note that `principal` here
#     is the clientInfo.name the client asserted during initialize — it is an
#     identity claim, not an authenticated one. On a real deployment the
#     principal comes from the authorization layer (the validated token
#     subject on the HTTP transport); clientInfo is self-reported and must
#     never be treated as authentication.
#
#     Also notice what was already correct and must stay that way: audit()
#     does not consult STATE["min_level"]. A client that sets its log level
#     to "emergency" silences the logging plane and changes nothing about the
#     audit trail. If a caller can turn off the record of their own actions,
#     you do not have an audit trail.
#
#   Verify
#     $ python3 client/mcp_probe.py >/dev/null && tail -n 1 var/log/mcp/audit.jsonl \
#         | python3 -m json.tool
