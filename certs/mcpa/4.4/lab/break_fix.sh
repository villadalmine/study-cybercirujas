write_rotate() {
    cat > "$LAB_ROOT/bin/rotate-now.sh" <<'ROTATE_SH'
#!/usr/bin/env bash
# rotate-now.sh - force one rotation of the audit trail.
#
# Uses the real logrotate binary when it is available, so the configuration
# under etc/logrotate.d is exercised exactly as it would be on a host. When
# logrotate is missing (or refuses), it falls back to a faithful emulation of
# the directives this lab uses: copytruncate, create, rotate N, postrotate.
set -uo pipefail

LAB_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CONF="$LAB_ROOT/etc/logrotate.d/mcp-audit.conf"
LOG="$LAB_ROOT/var/log/mcp/audit.jsonl"
STATE="$LAB_ROOT/var/run/logrotate.state"

[ -f "$CONF" ] || { printf 'missing config: %s\n' "$CONF" >&2; exit 1; }
[ -f "$LOG" ]  || : > "$LOG"

run_postrotate() {
    local block
    block="$(sed -n '/^[[:space:]]*postrotate/,/^[[:space:]]*endscript/p' "$CONF" | sed '1d;$d')"
    if [ -n "$block" ]; then
        printf 'emulation: running postrotate block\n'
        printf '%s\n' "$block" | /bin/sh
    fi
}

emulate_rotation() {
    printf 'emulation: rotating %s\n' "$LOG"
    if grep -qE '^[[:space:]]*copytruncate' "$CONF"; then
        cp -p "$LOG" "$LOG.1" 2>/dev/null || true
        : > "$LOG"
        run_postrotate
        return 0
    fi
    local i
    for i in 4 3 2 1; do
        if [ -f "$LOG.$i" ]; then mv -f "$LOG.$i" "$LOG.$((i + 1))"; fi
    done
    mv -f "$LOG" "$LOG.1"
    if grep -qE '^[[:space:]]*create' "$CONF"; then
        : > "$LOG"
        chmod 0640 "$LOG"
    fi
    run_postrotate
}

before_inode="$(stat -c %i "$LOG" 2>/dev/null || echo 0)"

if command -v logrotate >/dev/null 2>&1; then
    printf 'using logrotate: %s\n' "$(command -v logrotate)"
    logrotate --force --state "$STATE" "$CONF" 2>&1 || printf 'logrotate exited %d\n' "$?"
else
    printf 'logrotate not installed on this VM\n'
fi

after_inode="$(stat -c %i "$LOG" 2>/dev/null || echo 0)"
if [ "$before_inode" = "$after_inode" ] && [ ! -f "$LOG.1" ]; then
    printf 'no rotation observed, falling back to emulation\n'
    emulate_rotation
fi

printf 'post-rotation state:\n'
ls -l --time-style=+%%H:%%M:%%S "$LAB_ROOT/var/log/mcp/" | sed 's/^/  /'
ROTATE_SH
    chmod 0755 "$LAB_ROOT/bin/rotate-now.sh"
}

write_probe() {
    cat > "$LAB_ROOT/client/mcp_probe.py" <<'PROBE_PY'
#!/usr/bin/env python3
"""mcp-probe - a deliberately literal MCP client, used as a diagnostic tool.

It spawns the server over the stdio transport and drives one complete
session: initialize, initialized, logging/setLevel, tools/list, tools/call
(with a progressToken), then closes stdin.

Unlike a production client it does not give the server the benefit of the
doubt. Every line that arrives on stdout must parse as a JSON-RPC message,
and it calls logging/setLevel even when the capability was not advertised,
so that the failure mode is visible rather than assumed.

Usage:  mcp_probe.py [--json] [--timeout SECONDS] [--level LEVEL]
Exit:   0 clean session, 10 transport corruption, 11 protocol failure.
"""

import argparse
import json
import os
import queue
import subprocess
import sys
import threading

HERE = os.path.dirname(os.path.abspath(__file__))
LAB_ROOT = os.environ.get("LAB_ROOT") or os.path.dirname(HERE)
SERVER = os.path.join(LAB_ROOT, "server", "mcp_audit_server.py")
STDERR_LOG = os.path.join(LAB_ROOT, "var", "log", "mcp", "server.stderr.log")

CLIENT_INFO = {"name": "mcp-probe", "version": "0.3.0"}
PROTOCOL_VERSION = "2025-06-18"


class TransportCorruption(Exception):
    def __init__(self, line):
        super().__init__("non JSON-RPC data on stdout")
        self.line = line


class Session:
    def __init__(self, timeout):
        self.timeout = timeout
        self.errfh = open(STDERR_LOG, "ab")
        env = dict(os.environ)
        env["LAB_ROOT"] = LAB_ROOT
        # -u so the server's stdout is unbuffered: this probe measures what
        # the server writes, in the order it writes it.
        self.proc = subprocess.Popen(
            [sys.executable, "-u", SERVER],
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=self.errfh,
            cwd=LAB_ROOT,
            env=env,
            text=True,
            bufsize=1,
        )
        self.inbox = queue.Queue()
        self.reader = threading.Thread(target=self._pump, daemon=True)
        self.reader.start()

    def _pump(self):
        for line in self.proc.stdout:
            self.inbox.put(line.rstrip("\n"))
        self.inbox.put(None)

    def send(self, obj):
        self.proc.stdin.write(json.dumps(obj, separators=(",", ":")) + "\n")
        self.proc.stdin.flush()

    def recv(self):
        try:
            raw = self.inbox.get(timeout=self.timeout)
        except queue.Empty:
            raise TimeoutError("no message within %.1fs" % self.timeout)
        if raw is None:
            raise EOFError("server closed stdout")
        try:
            return json.loads(raw)
        except json.JSONDecodeError:
            raise TransportCorruption(raw)

    def await_response(self, request_id, collector):
        """Drain notifications until the matching response arrives."""
        while True:
            msg = self.recv()
            if "id" in msg and msg.get("id") == request_id:
                return msg
            method = msg.get("method", "")
            if method == "notifications/message":
                collector["log"].append(msg.get("params") or {})
            elif method == "notifications/progress":
                collector["progress"].append(msg.get("params") or {})
            else:
                collector["other"].append(msg)

    def close(self):
        try:
            self.proc.stdin.close()
        except Exception:
            pass
        try:
            self.proc.wait(timeout=3)
        except Exception:
            self.proc.kill()
        self.errfh.close()


def run(timeout, level):
    report = {
        "transport_clean": True,
        "offending_stdout_line": None,
        "handshake_ok": False,
        "protocol_version": None,
        "server_capabilities": None,
        "logging_capability": False,
        "set_level_ok": False,
        "set_level_error": None,
        "log_notifications": [],
        "info_logs": 0,
        "progress_notifications": 0,
        "tool_call_ok": False,
        "tool_rows": 0,
        "error": None,
    }
    collector = {"log": [], "progress": [], "other": []}
    session = Session(timeout)
    try:
        session.send({
            "jsonrpc": "2.0", "id": 1, "method": "initialize",
            "params": {
                "protocolVersion": PROTOCOL_VERSION,
                "capabilities": {},
                "clientInfo": CLIENT_INFO,
            },
        })
        init = session.await_response(1, collector)
        if "error" in init:
            report["error"] = "initialize failed: %s" % init["error"]
            return report, 11
        result = init.get("result") or {}
        report["handshake_ok"] = True
        report["protocol_version"] = result.get("protocolVersion")
        caps = result.get("capabilities") or {}
        report["server_capabilities"] = sorted(caps.keys())
        report["logging_capability"] = "logging" in caps

        session.send({"jsonrpc": "2.0", "method": "notifications/initialized"})

        # Called unconditionally: a probe reports what the server does, not
        # what its advertised capabilities promise.
        session.send({
            "jsonrpc": "2.0", "id": 2, "method": "logging/setLevel",
            "params": {"level": level},
        })
        set_level = session.await_response(2, collector)
        if "error" in set_level:
            report["set_level_error"] = set_level["error"]
        else:
            report["set_level_ok"] = True

        session.send({"jsonrpc": "2.0", "id": 3, "method": "tools/list", "params": {}})
        session.await_response(3, collector)

        session.send({
            "jsonrpc": "2.0", "id": 4, "method": "tools/call",
            "params": {
                "name": "query_records",
                "arguments": {"dataset": "incidents", "limit": 3},
                "_meta": {"progressToken": "probe-4"},
            },
        })
        call = session.await_response(4, collector)
        if "error" not in call:
            result = call.get("result") or {}
            report["tool_call_ok"] = not result.get("isError", False)
            try:
                payload = json.loads((result.get("content") or [{}])[0].get("text", "{}"))
                report["tool_rows"] = len(payload.get("rows", []))
            except (ValueError, IndexError, AttributeError):
                pass
    except TransportCorruption as exc:
        report["transport_clean"] = False
        report["offending_stdout_line"] = exc.line
        report["error"] = "stdout carried data that is not a JSON-RPC message"
        session.close()
        report["log_notifications"] = collector["log"]
        report["info_logs"] = sum(1 for m in collector["log"] if m.get("level") == "info")
        report["progress_notifications"] = len(collector["progress"])
        return report, 10
    except (TimeoutError, EOFError) as exc:
        report["error"] = str(exc)
        session.close()
        return report, 11
    finally:
        try:
            session.close()
        except Exception:
            pass

    report["log_notifications"] = collector["log"]
    report["info_logs"] = sum(1 for m in collector["log"] if m.get("level") == "info")
    report["progress_notifications"] = len(collector["progress"])
    return report, 0


def human(report, code):
    def mark(value):
        return "OK  " if value else "FAIL"

    print("MCP probe -> %s" % SERVER)
    print("-" * 71)
    print("  %s transport    stdout carries only JSON-RPC messages" % mark(report["transport_clean"]))
    if not report["transport_clean"]:
        print("       offending line: %r" % report["offending_stdout_line"])
        print("       on the stdio transport stdout IS the message channel;")
        print("       one stray byte desynchronises the whole session.")
    print("  %s handshake    protocolVersion=%s capabilities=%s"
          % (mark(report["handshake_ok"]), report["protocol_version"], report["server_capabilities"]))
    print("  %s logging cap  server advertises the logging capability" % mark(report["logging_capability"]))
    print("  %s setLevel     logging/setLevel accepted" % mark(report["set_level_ok"]))
    if report["set_level_error"]:
        print("       server answered: %s" % json.dumps(report["set_level_error"]))
    print("  %s log stream   %d notifications/message (%d at level=info)"
          % (mark(report["info_logs"] >= 2), len(report["log_notifications"]), report["info_logs"]))
    print("  %s progress     %d notifications/progress"
          % (mark(report["progress_notifications"] > 0), report["progress_notifications"]))
    print("  %s tools/call   query_records returned %d rows"
          % (mark(report["tool_call_ok"]), report["tool_rows"]))
    if report["error"]:
        print("\n  diagnosis: %s" % report["error"])
    print("\n  server stderr: %s" % STDERR_LOG)
    print("  exit code: %d" % code)


def main():
    parser = argparse.ArgumentParser(description="Drive one MCP session and report on it.")
    parser.add_argument("--json", action="store_true", help="emit the raw report as JSON")
    parser.add_argument("--timeout", type=float, default=8.0)
    parser.add_argument("--level", default="info")
    args = parser.parse_args()

    os.makedirs(os.path.dirname(STDERR_LOG), exist_ok=True)
    report, code = run(args.timeout, args.level)
    if args.json:
        print(json.dumps(report, indent=2))
    else:
        human(report, code)
    return code


if __name__ == "__main__":
    sys.exit(main())
PROBE_PY
    chmod 0755 "$LAB_ROOT/client/mcp_probe.py"
}

