# FAULT 4 — rotation orphans the relay's file descriptor
# -----------------------------------------------------------------------------
#
#   Diagnosis
#     $ bin/rotate-now.sh
#     $ ls -l /proc/$(cat var/run/relay.pid)/fd | grep mcp
#     l-wx------ 1 u u 64 Sep 17 10:09 4 -> /.../var/log/mcp/audit.jsonl.1
#     $ stat -c '%i %n' var/log/mcp/audit.jsonl*
#     2622013 var/log/mcp/audit.jsonl
#     2621998 var/log/mcp/audit.jsonl.1
#
#     The relay holds descriptor 4 open on inode 2621998. logrotate renamed
#     that inode to audit.jsonl.1 and created a fresh audit.jsonl — and never
#     told the writer. The process keeps appending, successfully, to a file
#     nobody reads; after `rotate 5` more cycles the inode is unlinked and
#     the target shows up as "(deleted)", at which point the records are
#     gone with no error anywhere. This is the classic way an audit trail
#     dies silently, and it is why CHECK 4 compares inodes instead of
#     trusting a successful write.
#
#   Fix (preferred) — etc/logrotate.d/mcp-audit.conf, add a postrotate hook
#   that signals the writer to reopen. Use the ABSOLUTE path to the pidfile:
#
#       /path/to/lab/var/log/mcp/audit.jsonl {
#           rotate 5
#           size 1k
#           missingok
#           notifempty
#           create 0640
#           sharedscripts
#           postrotate
#               /bin/kill -HUP "$(cat /path/to/lab/var/run/relay.pid)" 2>/dev/null || true
#           endscript
#       }
#
#     bin/audit-relay.py already implements the other half: SIGHUP sets a
#     flag, and the flag is consumed immediately before the next write, so
#     the descriptor is swapped without any record being written to the
#     retired one. It also stamps a {"event":"relay.reopen"} record into the
#     new file — cheap, and it makes "did the rotation land?" answerable from
#     the trail itself.
#
#   Fix (alternative) — add `copytruncate` and drop `create`:
#
#           copytruncate
#
#     logrotate copies the contents aside and truncates the original in
#     place, so the inode never changes and the writer needs no signal. It is
#     the right answer when you cannot modify or signal the producer, and the
#     wrong one for an audit trail you care about: there is a window between
#     copy and truncate in which records are lost, and no error is raised
#     when that happens. Prefer the signal; keep copytruncate for third-party
#     processes you do not control.
#     https://man7.org/linux/man-pages/man8/logrotate.8.html
#
#   Verify
#     $ bin/rotate-now.sh && sleep 1
#     $ ls -l /proc/$(cat var/run/relay.pid)/fd | grep mcp    # -> audit.jsonl, live inode
