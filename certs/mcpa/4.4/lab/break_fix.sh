      grep -n 'capabilities' server/mcp_audit_server.py
      grep -n 'setLevel\|min_level\|SEVERITY' server/mcp_audit_server.py

  Two separate questions, both required:
    * a client will not use a utility the server never advertised in the
      initialize result;
    * a message less severe than the current minimum level is dropped before
      it is ever sent - and nothing has moved that minimum off its default.
      https://modelcontextprotocol.io/specification/2025-06-18/server/utilities/logging
HINT2
    fi
    if [ "$which" = "all" ] || [ "$which" = "3" ]; then
        hdr "Hints for CHECK 3 - attributability"
        cat <<'HINT3'
      tail -n 3 var/log/mcp/audit.jsonl | python3 -m json.tool --json-lines 2>/dev/null \
        || tail -n 3 var/log/mcp/audit.jsonl

  Compare what the call sites pass in with what actually reaches the record:

      grep -n 'def audit\|audit(' server/mcp_audit_server.py

  An audit record must answer: when, what, WHO, and under WHICH request id.
  The values already exist in the process - one of them is even handed to
  the function as an argument and then thrown away.
HINT3
    fi
    if [ "$which" = "all" ] || [ "$which" = "4" ]; then
        hdr "Hints for CHECK 4 - durability across rotation"
        cat <<'HINT4'
      bin/relay-ctl.sh status
      ls -l /proc/$(cat var/run/relay.pid)/fd | grep mcp
      stat -c '%i %n' var/log/mcp/audit.jsonl*

  A process writes to an open descriptor, i.e. to an inode, not to a path.
  Renaming the file does not move the descriptor. Two ways out:

    * tell the rotator to signal the writer so it can reopen the path;
    * or tell the rotator to copy the contents and truncate in place.

  The relay already handles SIGHUP (see bin/audit-relay.py). Read what the
  configuration does NOT contain:
      https://man7.org/linux/man-pages/man8/logrotate.8.html
HINT4
    fi
}

cmd_reset() {
    assert_safe_root
    hdr "Resetting the lab"
    if [ -x "$LAB_ROOT/bin/relay-ctl.sh" ]; then
        "$LAB_ROOT/bin/relay-ctl.sh" stop >/dev/null 2>&1 || true
    fi
    rm -rf "${LAB_ROOT:?}"
    LAB_ASSUME_YES=1 cmd_break
}

cmd_cleanup() {
    assert_safe_root
    [ -d "$LAB_ROOT" ] || { say "nothing to clean up at $LAB_ROOT"; return 0; }
    if [ -x "$LAB_ROOT/bin/relay-ctl.sh" ]; then
        "$LAB_ROOT/bin/relay-ctl.sh" stop 2>&1 | sed 's/^/  /' || true
    fi
    rm -rf "${LAB_ROOT:?}"
    say "removed $LAB_ROOT"
}

main() {
    case "${1:-break}" in
        break|deploy|"") cmd_break ;;
        check|verify)    cmd_check ;;
        status)          cmd_status ;;
        hints|hint)      shift || true; cmd_hints "${1:-all}" ;;
        brief)           brief ;;
        reset)           cmd_reset ;;
        cleanup|destroy) cmd_cleanup ;;
        -h|--help|help)
            sed -n '2,60p' "$0" | sed 's/^# \{0,1\}//'
            ;;
        *) die "unknown subcommand: $1 (try --help)" ;;
    esac
}

