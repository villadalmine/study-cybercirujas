# WHAT THIS TOPIC ACTUALLY EXAMINES
# -----------------------------------------------------------------------------
#
#   1. The transport is a contract, not a convention. On stdio, stdout
#      carries framed JSON-RPC and nothing else; stderr is where a server
#      talks to its operator. On the Streamable HTTP transport the same
#      discipline applies to the response body — an unexpected byte before
#      the SSE frame breaks the client just as thoroughly.
#
#   2. Logging is a negotiated capability with a control plane. Declare
#      `logging` in the initialize result, honour logging/setLevel, filter by
#      RFC 5424 severity, attach a `logger` name so the client can route,
#      and keep credentials and PII out of `data`.
#
#   3. Observability and auditability are different requirements with
#      different owners. The client chooses how much it wants to see; nobody
#      gets to choose how much is recorded. Build the audit path so it cannot
#      be muted by a protocol message, and so a record answers when / what /
#      who / which request without a join against something else.
#
#   4. Durability is an operational property, not an application one. Correct
#      code writing to an orphaned descriptor reports nothing but records
#      nothing. Rotation policy, signal handling and descriptor hygiene are
#      part of the audit design, and the only honest test of them is to
#      rotate and then check where the bytes actually went.
