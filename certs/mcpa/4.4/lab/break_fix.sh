#
#  BREAK & FIX LAB — "the server that went quiet"
#
#  WHAT THIS SCRIPT DOES
#    It deploys a small but real MCP stack into a self-contained directory:
#
#      * an MCP server  (stdio transport, JSON-RPC 2.0, tools + logging)
#      * an MCP client  (a diagnostic probe that drives a full session)
#      * an audit relay (a long-lived sidecar that persists the audit trail)
#      * a logrotate configuration for that audit trail
#
#    and then breaks FOUR things across the two observability planes that
#    MCP keeps deliberately separate:
#
#      the LOGGING plane — notifications/message, verbosity controlled by the
#                          client through logging/setLevel; for the human.
#      the AUDIT  plane — an append-only JSON Lines record of who called what,
#                          never filtered by the client; for the auditor.
#
#  SAFETY
#    Nothing outside $LAB_ROOT is created, modified or deleted. No root, no
#    systemd units, no network listeners, no package installation, no writes
#    to /etc or /var. The only long-lived process is the audit relay, started
#    from $LAB_ROOT and stopped with "$0 cleanup". It is still meant for a
#    disposable lab VM: you will be editing files and killing processes.
#
#  REQUIREMENTS
#    Linux, bash 4+, python3 >= 3.8, coreutils. logrotate optional (a faithful
#    shell emulation is used when it is absent).
#
#  USAGE
#    ./mcpa-4.4-break-fix.sh                 deploy the stack, break it, brief you
#    ./mcpa-4.4-break-fix.sh check           run the acceptance gate
#    ./mcpa-4.4-break-fix.sh status          show the live state of the stack
#    ./mcpa-4.4-break-fix.sh hints [1-4]     diagnostic hints (commands, not answers)
#    ./mcpa-4.4-break-fix.sh reset           re-deploy the broken stack from scratch
#    ./mcpa-4.4-break-fix.sh cleanup         stop the relay and remove $LAB_ROOT
#
#    Environment: LAB_ROOT=/path/to/lab   (default: $HOME/mcp-audit-lab)
#                 LAB_ASSUME_YES=1        (skip the confirmation prompt)
#
