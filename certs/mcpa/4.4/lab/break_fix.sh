# -----------------------------------------------------------------------------
# FAULT 1 — the server logs to stdout on the stdio transport
# -----------------------------------------------------------------------------
#
#   Diagnosis
#     $ cd "$LAB_ROOT"
#     $ printf '%s\n' '{"jsonrpc":"2.0","id":1,"method":"initialize","params":{"protocolVersion":"2025-06-18","capabilities":{},"clientInfo":{"name":"x","version":"0"}}}' \
#         | python3 -u server/mcp_audit_server.py | head -n 2
#     2026-09-17T10:04:11.882Z records-audit[41233]: v1.4.0 starting, audit sink /.../audit.fifo
#     {"jsonrpc":"2.0","id":1,"result":{"protocolVersion":"2025-06-18", ...}}
#
#     The first line is not a JSON-RPC message. On the stdio transport the
#     server's stdout IS the message channel — newline-delimited JSON-RPC and
#     nothing else. The spec is explicit: the server MUST NOT write anything
#     to stdout that is not a valid MCP message, and MAY write UTF-8 to
#     stderr for logging.
#     https://modelcontextprotocol.io/specification/2025-06-18/basic/transports
#
#     Any conformant client throws a parse error on that first read, which is
#     why the failure looks like "the server is broken" rather than "someone
#     left a banner in". Note that the banner only appears first because the
#     probe runs the server with -u; with block buffering the same bug shows
#     up as a session that works for a while and then dies mid-stream. The
#     nondeterminism is the bug, not a mitigation.
#
#   Fix — server/mcp_audit_server.py, function _console():
#
#       def _console(text: str) -> None:
#           """Operator-facing, human-readable line. Not a protocol message."""
#           print("%s records-audit[%d]: %s" % (_ts(), os.getpid(), text),
#                 file=sys.stderr, flush=True)
#
#     One line. Every operator-facing message in this server funnels through
#     _console(), which is the point: a single chokepoint for the one stream
#     that must never touch stdout. In your own servers, do the same thing at
#     the framework level — configure the logging handler onto sys.stderr and
#     forbid bare print() in review.
#
#   Verify
#     $ python3 client/mcp_probe.py
#       OK   transport    stdout carries only JSON-RPC messages
#     $ tail -n 2 var/log/mcp/server.stderr.log        # the banner lives here now
#
# -----------------------------------------------------------------------------
# FAULT 2 — the logging capability is not advertised and setLevel is stubbed out
# -----------------------------------------------------------------------------
#
#   Diagnosis
#     $ python3 client/mcp_probe.py
#       OK   handshake    protocolVersion=2025-06-18 capabilities=['tools']
#       FAIL logging cap  server advertises the logging capability
#       FAIL setLevel     logging/setLevel accepted
#            server answered: {"code": -32601, "message": "Method not found: logging/setLevel"}
#       FAIL log stream   1 notifications/message (0 at level=info)
#
#     Two independent defects with one symptom. The initialize result does
#     not declare `logging`, so a real client will never offer the user a
#     verbosity control at all; and even a client that tries anyway is told
#     the method does not exist. Meanwhile STATE["min_level"] sits at its
#     "warning" default, so every info-level message about tool execution is
#     dropped before it reaches the wire. The tool works; nobody can watch it.
#
#   Fix — server/mcp_audit_server.py, in dispatch(), initialize branch:
#
#           return ok(mid, {
#               "protocolVersion": PROTOCOL_VERSION,
#               "capabilities": {
#                   "tools": {"listChanged": False},
#                   "logging": {},                     # <-- declare the utility
#               },
#               "serverInfo": SERVER_INFO,
#               "instructions": "Query incident records. All calls are audited.",
#           })
#
#   Fix — replace the logging/setLevel stub with a real handler:
#
#       if method == "logging/setLevel":
#           level = (params or {}).get("level")
#           if level not in SEVERITY:
#               audit("logging.setlevel.rejected", request_id=mid, level=level)
#               return err(mid, -32602, "Invalid level: %r" % level,
#                          {"supported": sorted(SEVERITY, key=SEVERITY.get)})
#           previous = STATE["min_level"]
#           STATE["min_level"] = level
#           audit("logging.setlevel", request_id=mid, previous=previous, level=level)
#           log_message("notice", "logging", {"min_level": level, "previous": previous})
#           return ok(mid, {})
#
#     Points worth internalising:
#       * levels are RFC 5424 severities (debug .. emergency), and setting a
#         level means "send me this level and everything MORE severe" — the
#         comparison in log_message() is SEVERITY[level] <= SEVERITY[minimum]
#         because lower numbers are more severe;
#         https://modelcontextprotocol.io/specification/2025-06-18/server/utilities/logging
#         https://datatracker.ietf.org/doc/html/rfc5424
#       * an unknown level is -32602 (Invalid params), not -32601;
#       * the level change is itself an audited event. "Who turned the
#         logging down, and when" is a question incident reviews really ask;
#       * never put secrets, tokens or PII in `data` — notifications/message
#         is client-visible by design, and rate-limiting the stream is the
#         server's job.
#
#   Verify
#     $ python3 client/mcp_probe.py
#       OK   logging cap  server advertises the logging capability
#       OK   setLevel     logging/setLevel accepted
#       OK   log stream   3 notifications/message (2 at level=info)
