| `gateway/policy.json` | **yes - fix it** |
| `gateway/server_fileops.py` | no - a remote server, untrusted, unpatchable |
| `attack.json`, `approve.json` | no - the adversary's input and a benign call |
| `reset.sh`, `verify.sh` | no - the grader |
