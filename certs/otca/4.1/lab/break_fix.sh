#  SOLUTION  (step by step — try it yourself before reading)
# ==============================================================================
#
#  1) See what is misconfigured:
#
#        cd /tmp/otca-4.1-context-propagation
#        cat propagation.env
#        # -> OTEL_PROPAGATORS=none
#
#     `none` is the no-op propagator. With it, propagate.inject() writes nothing
#     onto the carrier and propagate.extract() returns an empty Context, so the
#     SpanContext (trace_id / span_id / trace-flags) and the Baggage never cross
#     the A -> B boundary. Each service therefore starts its own root trace.
#
#  2) Restore the standard propagators. The OpenTelemetry SDK default is the
#     W3C Trace Context propagator (carries the `traceparent` header) plus the
#     W3C Baggage propagator (carries the `baggage` header):
#
#        echo 'OTEL_PROPAGATORS=tracecontext,baggage' > propagation.env
#
#     (Equivalently, `unset OTEL_PROPAGATORS` / delete the line falls back to
#     the same built-in default: tracecontext,baggage.)
#
#  3) Re-run and confirm:
#
#        bash run.sh
#
#     Expected, now-correct output:
#        [wire] headers handed to Service B:
#            traceparent: 00-<32-hex trace_id>-<16-hex span_id>-01
#            baggage: user.id=42
#        [Service A] trace_id = <X>
#        [Service B] trace_id = <X>          # SAME as A
#        [Service B] parent   = <A.span_id>  # B is a child of A
#        [Service B] baggage user.id = 42    # baggage preserved
#        RESULT: LINKED (ok)
#
#  4) Why this is the whole point of Topic 4.1:
#       - "Context" (trace_id, span_id, trace-flags, plus Baggage) lives only
#         inside a process. To keep a distributed trace connected it must be
#         serialized on the way OUT (inject, by the producer) and rebuilt on the
#         way IN (extract, by the consumer).
#       - A Propagator is what does that serialization. `tracecontext` encodes
#         the SpanContext into the W3C `traceparent` header (format
#         `version-traceid-parentid-traceflags`, e.g. 00-<32hex>-<16hex>-01);
#         `baggage` encodes key/value Baggage into the W3C `baggage` header.
#       - Misconfiguring OTEL_PROPAGATORS (to `none`, or omitting the one a
#         downstream service expects, e.g. b3 vs tracecontext mismatch) silently
#         severs traces: instrumentation still runs, spans still export, but they
#         no longer share a trace_id. That silent break is exactly what the exam
#         wants you to recognize and repair.
#
#  Optional experiments to deepen understanding:
#     * OTEL_PROPAGATORS=b3multi   -> B3 multi-header format (X-B3-TraceId, ...)
#     * OTEL_PROPAGATORS=b3        -> B3 single-header format (b3: trace-span-...)
#       Both still LINK A and B here because A and B share the global propagator.
#       Now set DIFFERENT propagators for the two sides to reproduce a real
#       cross-vendor mismatch and watch the trace fragment again.
