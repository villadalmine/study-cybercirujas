cat > demo.py <<'PYEOF'
import os
from opentelemetry import trace, propagate, baggage, context
from opentelemetry.sdk.trace import TracerProvider

trace.set_tracer_provider(TracerProvider())
tracer = trace.get_tracer("otca.topic-4.1.context-propagation")

hex32 = lambda n: format(n, "032x")   # trace_id -> 32 hex chars
hex16 = lambda n: format(n, "016x")   # span_id  -> 16 hex chars

print("=" * 70)
print("OTEL_PROPAGATORS =",
      os.getenv("OTEL_PROPAGATORS", "<unset -> default: tracecontext,baggage>"))
print("=" * 70)

# --- SERVICE A (producer / client) -------------------------------------------
# A starts a span and attaches request-scoped Baggage, then injects the current
# Context into an outgoing carrier (what would be the HTTP request headers).
carrier = {}
token = context.attach(baggage.set_baggage("user.id", "42"))
with tracer.start_as_current_span("A.checkout") as span_a:
    a = span_a.get_span_context()
    a_trace, a_span = hex32(a.trace_id), hex16(a.span_id)
    propagate.inject(carrier)          # writes traceparent/baggage IF a propagator is active
context.detach(token)

print("\n[Service A]  trace_id =", a_trace)
print("[Service A]  span_id  =", a_span)
print("[wire]       headers handed to Service B:")
if carrier:
    for k, v in carrier.items():
        print("               {}: {}".format(k, v))
else:
    print("               << EMPTY -- nothing was injected onto the wire >>")

# --- network boundary --------------------------------------------------------
# In production the carrier crosses the network as HTTP headers. Here we simply
# pass the same dict to Service B, exactly as a server would receive headers.

# --- SERVICE B (consumer / server) -------------------------------------------
# B extracts the incoming Context from the carrier and starts its span inside it.
extracted = propagate.extract(carrier)
b_bag = baggage.get_baggage("user.id", extracted)
with tracer.start_as_current_span("B.charge", context=extracted) as span_b:
    b = span_b.get_span_context()
    b_trace = hex32(b.trace_id)
    b_parent = span_b.parent

print("\n[Service B]  trace_id =", b_trace)
print("[Service B]  parent   =",
      hex16(b_parent.span_id) if b_parent else "<none -- B started a BRAND-NEW trace>")
print("[Service B]  baggage user.id =", b_bag if b_bag is not None else "<lost>")

print("\n" + "-" * 70)
if b_trace == a_trace and b_parent is not None:
    print("RESULT: LINKED  (ok)  -> A and B share ONE trace; B is a child of A;")
    print("                        baggage survived the hop.")
else:
    print("RESULT: BROKEN  (fail) -> A and B are in DIFFERENT traces. The request")
    print("                        looks like two unrelated operations and baggage")
    print("                        never reached B.")
print("-" * 70)
PYEOF

