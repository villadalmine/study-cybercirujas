#     Caution: invalid main GPT header, but valid backup; regenerating main header
#     using backup!
#     Warning: Invalid CRC on main header data; loaded backup partition table.
#     ...
#     Partition table scan:
#       MBR: not present
#       BSD: not present
#       APM: not present
#       GPT: damaged
#
#   That single line - "valid backup" - is the whole reason this is repairable.
#   A GPT disk carries TWO copies of the header and of the partition entry
#   array: the primary at LBA 1 (entries at LBA 2-33) and the backup in the
#   LAST sectors of the disk. Only the primary was destroyed.
#
# -----------------------------------------------------------------------------
#  STEP 1 - rebuild the primary GPT from the backup GPT
# -----------------------------------------------------------------------------
#   gdisk /dev/loopX
#     r        <- recovery & transformation menu
#     b        <- use the backup GPT header to rebuild the main header
#     v        <- verify: should now report "No problems found"
#     p        <- print the table; check the three partitions are back with
#                 their sizes (600 MiB / 128 MiB / 128 MiB), type codes
#                 8300 / 0700 / 8200 and names lpic-data / lpic-vfat / lpic-swap
#     w        <- write the table to disk and confirm with 'Y'
#
#   Equivalent non-interactive form (sgdisk loads the backup automatically when
#   the primary is unreadable, so simply writing the table back repairs it):
#     sgdisk --verify /dev/loopX
#     sgdisk --move-second-header /dev/loopX      # rewrites both copies
#
#   Then make the KERNEL re-read the table - writing it to disk is not enough:
#     partx -a /dev/loopX        # or: partprobe /dev/loopX
#     lsblk /dev/loopX
#
#   You should now see loopXp1, loopXp2 and loopXp3 again. Verify immediately
#   that the untouched partition is healthy - that is your proof the offsets
#   are correct and not merely plausible:
#     mount -o ro /dev/loopXp2 /mnt && ls -l /mnt && umount /mnt
#
#   Note on MBR disks: the same accident on MBR (dd of the first 512 bytes) is
#   NOT recoverable this way, because MBR keeps a single copy of the table.
#   That is why `sfdisk --dump /dev/sda > table.txt` (restored with
#   `sfdisk /dev/sda < table.txt`) belongs in every backup plan.
#
# -----------------------------------------------------------------------------
#  STEP 2 - recover the ext4 filesystem from a backup superblock
# -----------------------------------------------------------------------------
#   Confirm the damage first:
#     blkid /dev/loopXp1                 # prints nothing
#     dumpe2fs -h /dev/loopXp1           # "Couldn't find valid filesystem superblock"
#     mount /dev/loopXp1 /mnt            # "can't read superblock"
#
#   Find the backup superblocks. mke2fs -n computes the layout it WOULD create
#   and writes nothing at all - it is the safe way to ask "where would the
#   backups be?" for a filesystem created with the same defaults:
#
#     mke2fs -n /dev/loopXp1
#       ...
#       Superblock backups stored on blocks:
#               32768, 98304
#
#   (dumpe2fs on a healthy ext4 shows the same numbers. With the default
#   sparse_super feature, backups live in block groups 1, 3, 5, 7, 9, 25, 27,
#   49, 81 ... - with 4 KiB blocks and 32768 blocks per group, group 1 starts
#   at block 32768. On a filesystem smaller than 512 MiB mke2fs picks 1 KiB
#   blocks instead and the first backup is at block 8193 - always ASK the tool,
#   never memorise one number.)
#
#   Repair using the backup. -b selects the alternate superblock, -B states the
#   block size explicitly because the primary superblock that would normally
#   declare it is gone, -f forces a full check and -y answers yes to every
#   question:
#
#     e2fsck -f -y -b 32768 -B 4096 /dev/loopXp1
#
#   Expected output (abridged):
#     Pass 1: Checking inodes, blocks, and sizes
#     Pass 2: Checking directory structure
#     Pass 3: Checking directory connectivity
#     Pass 4: Checking reference counts
#     Pass 5: Checking group summary information
#     Free blocks count wrong for group #0 (...): FIXED
#     LPICDATA: ***** FILE SYSTEM WAS MODIFIED *****
#
#   e2fsck copies the backup superblock and the backup group descriptors over
#   the primary ones when it writes out, so the filesystem is fully repaired,
#   not just readable through a detour. Confirm and re-check:
#
#     e2fsck -f -y /dev/loopXp1          # second run must be clean
#     blkid /dev/loopXp1                 # LABEL="LPICDATA" TYPE="ext4"
#     mount /dev/loopXp1 /mnt
#     ls -l /mnt/payroll | head          # 24 slips + CANARY.txt
#     cat /mnt/payroll/CANARY.txt
#     umount /mnt
#
#   If files had ended up in /mnt/lost+found, that is e2fsck telling you it
#   reconnected orphaned inodes - inspect them there before declaring victory.
#
#   What you must NOT do: mkfs.ext4 /dev/loopXp1. It succeeds instantly, the
#   partition mounts, every check except the data check goes green, and the
#   payroll files are gone forever.
#
# -----------------------------------------------------------------------------
#  STEP 3 - rebuild the swap area
# -----------------------------------------------------------------------------
#   Swap holds no persistent data, so re-creating the structure is correct:
#
#     blkid /dev/loopXp3                 # prints nothing - signature gone
#     mkswap -L LPICSWAP /dev/loopXp3
#       Setting up swapspace version 1, size = 128 MiB (134213632 bytes)
#       LABEL=LPICSWAP, UUID=....
#     swapon /dev/loopXp3
#     swapon --show                      # or: cat /proc/swaps
#     swapoff /dev/loopXp3
#
#   Two details the exam likes:
#     * mkswap generates a NEW UUID. Any /etc/fstab entry written as
#       UUID=<old> will now fail at boot - re-read the UUID with
#       `blkid /dev/loopXp3` and update fstab (or use LABEL=, which mkswap -L
#       preserved on purpose).
#     * The GPT type code 8200 does not make a partition swap; only mkswap
#       does. The type code is metadata for tools and firmware. Conversely,
#       systemd-gpt-auto-generator DOES act on 8200, so on a real system a
#       correct type code is what makes swap activate without an fstab entry.
#
# -----------------------------------------------------------------------------
#  STEP 4 - verify like an SRE, not like a student
# -----------------------------------------------------------------------------
#     lsblk -o NAME,SIZE,TYPE,FSTYPE,LABEL,UUID /dev/loopX
#     sgdisk -v /dev/loopX               # "No problems found"
#     e2fsck -fn /dev/loopXp1            # clean, and it modified nothing
#     sudo ./104.1-break-and-fix.sh check
#
# -----------------------------------------------------------------------------
#  WHAT TO TAKE AWAY
# -----------------------------------------------------------------------------
#   1. Redundancy is on the disk already: GPT keeps a backup header + entry
#      array at the end of the device; ext2/3/4 keeps backup superblocks and
#      group descriptors in selected block groups. Both are free, both are
#      already there, and both are useless if you do not know they exist.
#   2. Writing a partition table and having the kernel USE it are two separate
#      events - partx -a / partprobe / blockdev --rereadpt bridge them, and a
#      busy device may refuse the re-read until you unmount.
#   3. The order of repair is bottom-up: partition table, then filesystem
#      metadata, then activation (mount / swapon). Debugging a mount failure
#      before the partition even exists is wasted effort.
#   4. mkfs is never a repair. It is the fastest way to convert a recoverable
#      incident into a permanent one.
#   5. Before any partitioning work on a real machine:
#        sfdisk --dump /dev/sda > /root/sda.table          # MBR and GPT
#        sgdisk --backup=/root/sda.gpt /dev/sda            # GPT, binary
#        blkid > /root/blkid.txt                           # UUIDs for fstab
# =============================================================================