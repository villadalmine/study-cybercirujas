#!/usr/bin/env bash
#
# ============================================================================
#  LPIC-1 (101-500 / 102-500) — Topic 107.2
#  Automate system administration tasks by scheduling jobs
#
#  BREAK & FIX LABORATORY — cron / anacron / at / systemd timers
#
#  WARNING: THIS SCRIPT INTENTIONALLY BREAKS JOB SCHEDULING ON THIS MACHINE.
#  Run it ONLY inside a disposable lab VM (snapshot it first).
#  It must be run as root. It never touches user data outside the paths
#  it creates, and every original file it modifies is backed up under
#  /root/107.2-lab-backup/ so an instructor can always recover the box.
#
#  Reference: LPI Exam 101/102 objectives — https://www.lpi.org/our-certifications/exam-101-objectives/
#             crontab(5), crontab(1), cron(8), anacrontab(5), at(1),
#             systemd.timer(5), systemd.time(7)
# ============================================================================

set -o nounset
set -o pipefail

readonly LAB_TAG="107.2"
readonly BACKUP_DIR="/root/107.2-lab-backup"
readonly REPORT_DIR="/var/log/billing-report"
readonly REPORT_SCRIPT="/usr/local/bin/billing-report.sh"
readonly LAB_USER="billing"
readonly SYSTEM_CRON_FILE="/etc/cron.d/billing-report"
readonly ANACRON_JOB="/etc/cron.daily/billing-rotate"
readonly TIMER_UNIT="/etc/systemd/system/billing-metrics.timer"
readonly SERVICE_UNIT="/etc/systemd/system/billing-metrics.service"
readonly METRICS_FILE="/var/lib/billing-metrics.txt"

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

say()  { printf '\033[1;36m[%s]\033[0m %s\n' "$LAB_TAG" "$*"; }
warn() { printf '\033[1;33m[%s]\033[0m %s\n' "$LAB_TAG" "$*"; }
die()  { printf '\033[1;31m[%s] FATAL:\033[0m %s\n' "$LAB_TAG" "$*" >&2; exit 1; }

require_root() {
    [ "$(id -u)" -eq 0 ] || die "This lab must be run as root (try: sudo $0)."
}

require_lab_vm() {
    # Cheap guard rails. A disposable lab VM is expected; refuse on anything
    # that looks like it might matter to someone.
    if [ -f /etc/lpi-lab-vm ]; then
        return 0
    fi
    cat <<'EOF'

  ###################################################################
  #  This script DELIBERATELY BREAKS cron, at, and systemd timers.  #
  #  Only run it on a THROWAWAY lab VM you can roll back.           #
  ###################################################################

EOF
    printf 'Type exactly  BREAK MY LAB VM  to continue: '
    read -r confirmation
    [ "$confirmation" = "BREAK MY LAB VM" ] || die "Aborted. Nothing was changed."
    : > /etc/lpi-lab-vm
}

backup_file() {
    # backup_file <path> — preserve the original once, never overwrite a backup
    local src="$1"
    local dst="$BACKUP_DIR/$(printf '%s' "${src#/}" | tr '/' '_')"
    mkdir -p "$BACKUP_DIR"
    if [ -e "$src" ] && [ ! -e "$dst" ]; then
        cp -a "$src" "$dst"
    fi
}

detect_cron_service() {
    # Debian/Ubuntu call it cron.service; RHEL/Fedora/SUSE call it crond.service
    if systemctl list-unit-files 2>/dev/null | grep -q '^crond\.service'; then
        printf 'crond'
    elif systemctl list-unit-files 2>/dev/null | grep -q '^cron\.service'; then
        printf 'cron'
    else
        printf 'cron'
    fi
}

detect_at_service() {
    if systemctl list-unit-files 2>/dev/null | grep -q '^atd\.service'; then
        printf 'atd'
    else
        printf 'atd'
    fi
}

# ---------------------------------------------------------------------------
# Scenario setup — build a plausible, working production-ish job set FIRST,
# so the student sees a system that used to work and now does not.
# ---------------------------------------------------------------------------

build_working_scenario() {
    say "Building the 'before' state: a working scheduled billing pipeline..."

    getent passwd "$LAB_USER" >/dev/null 2>&1 || \
        useradd --create-home --shell /bin/bash --comment "Billing batch user" "$LAB_USER"

    mkdir -p "$REPORT_DIR"
    chown "$LAB_USER:$LAB_USER" "$REPORT_DIR"

    cat > "$REPORT_SCRIPT" <<'SCRIPT'
#!/bin/bash
# Billing report generator. Appends one line per successful run.
# Deliberately trivial: this lab is about SCHEDULING, not about the payload.
set -euo pipefail
OUT="/var/log/billing-report/report.log"
mkdir -p "$(dirname "$OUT")"
printf '%s billing report generated by %s (PATH=%s)\n' \
    "$(date --iso-8601=seconds)" "$(id -un)" "${PATH}" >> "$OUT"
SCRIPT
    chmod 0755 "$REPORT_SCRIPT"

    # A per-user crontab for the billing user, installed the supported way.
    crontab -u "$LAB_USER" - <<'CRONTAB'
# Billing pipeline — per-user crontab (crontab -e as the billing user)
MAILTO=""
*/2 * * * * /usr/local/bin/billing-report.sh
CRONTAB

    # A system-wide crontab fragment, which carries a USER field (crontab(5)).
    cat > "$SYSTEM_CRON_FILE" <<'CRONDFILE'
# /etc/cron.d/billing-report — system crontab fragment.
# NOTE the sixth field: system crontabs take a user name, user crontabs do not.
SHELL=/bin/bash
PATH=/usr/local/sbin:/usr/local/bin:/sbin:/bin:/usr/sbin:/usr/bin
*/5 * * * *  root  /usr/local/bin/billing-report.sh
CRONDFILE
    chmod 0644 "$SYSTEM_CRON_FILE"

    # An anacron-style daily job (/etc/cron.daily is run by anacron or by the
    # cron daily wrapper depending on the distribution).
    cat > "$ANACRON_JOB" <<'DAILY'
#!/bin/sh
# Rotate yesterday's billing report. Run out of /etc/cron.daily.
LOG=/var/log/billing-report/report.log
[ -f "$LOG" ] && mv "$LOG" "$LOG.$(date +%Y%m%d)"
exit 0
DAILY
    chmod 0755 "$ANACRON_JOB"

    # A systemd timer doing the same class of work the modern way.
    cat > "$SERVICE_UNIT" <<'SERVICE'
[Unit]
Description=Collect billing metrics

[Service]
Type=oneshot
ExecStart=/bin/sh -c 'echo "$(date --iso-8601=seconds) metrics collected" >> /var/lib/billing-metrics.txt'
SERVICE

    cat > "$TIMER_UNIT" <<'TIMER'
[Unit]
Description=Collect billing metrics every 3 minutes

[Timer]
OnCalendar=*:0/3
Persistent=true
Unit=billing-metrics.service

[Install]
WantedBy=timers.target
TIMER

    systemctl daemon-reload >/dev/null 2>&1 || true
    systemctl enable --now billing-metrics.timer >/dev/null 2>&1 || \
        warn "Could not enable billing-metrics.timer (is this a systemd host?)."

    local cron_svc at_svc
    cron_svc="$(detect_cron_service)"
    at_svc="$(detect_at_service)"
    systemctl enable --now "${cron_svc}.service" >/dev/null 2>&1 || \
        warn "Could not start ${cron_svc}.service."
    systemctl enable --now "${at_svc}.service"   >/dev/null 2>&1 || \
        warn "Could not start ${at_svc}.service — install the 'at' package if missing."

    : > "$METRICS_FILE" 2>/dev/null || true

    say "Baseline built. All four scheduling mechanisms are configured and running."
}

# ---------------------------------------------------------------------------
# THE BREAKAGE
#
# Five independent faults, each one a classic 107.2 failure mode. They are
# deliberately *plausible*: every one of them is something a real admin has
# done to a real box on a Friday afternoon.
# ---------------------------------------------------------------------------

break_1_cron_deny() {
    # cron.allow / cron.deny (crontab(1), cron(8) ACCESS CONTROL).
    # If cron.allow exists, ONLY the users listed in it may use crontab.
    # Here we create a cron.allow that omits the billing user, so the user is
    # locked out of their own crontab. Note cron.allow wins over cron.deny.
    say "Fault 1/5: tightening crontab access control..."
    local dir
    for dir in /etc /etc/cron.d; do :; done
    backup_file /etc/cron.allow
    backup_file /etc/cron.deny
    rm -f /etc/cron.deny
    cat > /etc/cron.allow <<'ALLOW'
root
operations
ALLOW
    chmod 0600 /etc/cron.allow

    backup_file /etc/at.deny
    backup_file /etc/at.allow
    rm -f /etc/at.allow
    # at.deny lists users who may NOT use at/batch.
    printf '%s\n' "$LAB_USER" >> /etc/at.deny
    chmod 0640 /etc/at.deny
}

break_2_corrupt_user_crontab() {
    # Two faults in one file, both invisible until you actually read crontab(5):
    #   a) a six-field line in a USER crontab — the sixth field is parsed as
    #      part of the command, or the line is rejected entirely.
    #   b) an unescaped '%' in the command. In crontab(5) a bare % means
    #      "newline, and everything after it is stdin for the command".
    #   c) DOW/DOM interaction: when BOTH day-of-month and day-of-week are
    #      restricted, cron runs the job if EITHER matches (an OR, not an AND).
    say "Fault 2/5: rewriting the ${LAB_USER} crontab..."
    crontab -u "$LAB_USER" -l > "$BACKUP_DIR/crontab.${LAB_USER}" 2>/dev/null || true

    # Write the broken crontab directly into the spool so that the syntax
    # checks in crontab(1) do not save the student from the exercise.
    local spool
    for spool in /var/spool/cron/crontabs /var/spool/cron; do
        [ -d "$spool" ] || continue
        cat > "${spool}/${LAB_USER}" <<'BADCRON'
# Billing pipeline — per-user crontab
MAILTO=""
# Report is supposed to run every two minutes:
*/2 * * * * billing /usr/local/bin/billing-report.sh
# Month-end stamp, "only on the 1st, and only on Mondays":
0 6 1 * 1 /usr/bin/date +%Y-%m-%d >> /var/log/billing-report/stamp.log
BADCRON
        chown "$LAB_USER:crontab" "${spool}/${LAB_USER}" 2>/dev/null || \
            chown "$LAB_USER:$LAB_USER" "${spool}/${LAB_USER}" 2>/dev/null || true
        chmod 0600 "${spool}/${LAB_USER}"
        break
    done
}

break_3_environment_and_perms() {
    # The single most common cron complaint on the planet: "it works when I
    # run it by hand and does nothing from cron". cron gives the job a
    # minimal environment — no ~/.bashrc, no ~/.profile, a short PATH — and
    # here we make the script depend on something only an interactive login
    # would have, then also strip its execute bit.
    say "Fault 3/5: adjusting the report script and its environment..."
    backup_file "$REPORT_SCRIPT"
    cat > "$REPORT_SCRIPT" <<'SCRIPT'
#!/bin/bash
set -euo pipefail
# BILLING_HOME comes from /etc/profile.d/billing.sh, which cron never sources.
OUT="${BILLING_HOME}/report.log"
# 'billing-helper' lives in /opt/billing/bin, which is only on an interactive PATH.
billing-helper >> "$OUT"
SCRIPT
    chmod 0644 "$REPORT_SCRIPT"   # execute bit intentionally removed

    mkdir -p /opt/billing/bin
    cat > /opt/billing/bin/billing-helper <<'HELPER'
#!/bin/bash
printf '%s billing report generated by %s\n' "$(date --iso-8601=seconds)" "$(id -un)"
HELPER
    chmod 0755 /opt/billing/bin/billing-helper

    cat > /etc/profile.d/billing.sh <<'PROFILE'
export BILLING_HOME=/var/log/billing-report
export PATH="$PATH:/opt/billing/bin"
PROFILE
    chmod 0644 /etc/profile.d/billing.sh
}

break_4_crond_file_rules() {
    # /etc/cron.d and /etc/cron.daily files are silently ignored when they
    # break run-parts / cron naming and permission rules:
    #   - run-parts skips names containing a dot or other invalid characters
    #   - cron refuses /etc/cron.d files that are group- or world-writable
    #   - a crontab file whose last line has no trailing newline may be skipped
    say "Fault 4/5: renaming and re-permissioning the drop-in job files..."
    backup_file "$SYSTEM_CRON_FILE"
    backup_file "$ANACRON_JOB"

    # cron.d fragment: given a suffix run-parts/cron will not accept, made
    # world-writable, and stripped of its trailing newline.
    rm -f "$SYSTEM_CRON_FILE"
    printf '%s' \
'SHELL=/bin/bash
PATH=/usr/local/sbin:/usr/local/bin:/sbin:/bin:/usr/sbin:/usr/bin
*/5 * * * *  root  /usr/local/bin/billing-report.sh' \
        > /etc/cron.d/billing-report.bak
    chmod 0666 /etc/cron.d/billing-report.bak

    # cron.daily job: execute bit removed, so run-parts will not run it.
    chmod 0644 "$ANACRON_JOB" 2>/dev/null || true

    # And anacron is told the job already ran today, plus a delay long enough
    # that it will not fire again in this lab session.
    backup_file /etc/anacrontab
    if [ -f /etc/anacrontab ]; then
        sed -i 's/^START_HOURS_RANGE=.*/START_HOURS_RANGE=3-4/' /etc/anacrontab 2>/dev/null || true
    fi
    if [ -d /var/spool/anacron ]; then
        backup_file /var/spool/anacron/cron.daily
        date +%Y%m%d > /var/spool/anacron/cron.daily 2>/dev/null || true
    fi
}

break_5_systemd_timer() {
    # systemd timers fail in their own idioms:
    #   - an OnCalendar expression that is syntactically valid but means
    #     something the admin did not intend (or is simply invalid, which
    #     makes the unit fail to load)
    #   - Unit= pointing at a service that does not exist
    #   - the timer left disabled after an edit, so nothing is ever queued
    say "Fault 5/5: editing the systemd timer..."
    backup_file "$TIMER_UNIT"
    backup_file "$SERVICE_UNIT"

    systemctl disable --now billing-metrics.timer >/dev/null 2>&1 || true

    cat > "$TIMER_UNIT" <<'TIMER'
[Unit]
Description=Collect billing metrics every 3 minutes

[Timer]
# Intended: every 3 minutes. This is not that.
OnCalendar=*-*-* *:*:00/3
Persistent=true
Unit=billing-metric.service

[Install]
WantedBy=timers.target
TIMER

    systemctl daemon-reload >/dev/null 2>&1 || true
}

break_6_stop_the_daemons() {
    # Nothing scheduled runs if the scheduler is not running. Both daemons are
    # stopped AND masked, so a plain 'systemctl start' returns an error the
    # student has to read carefully.
    say "Fault 6/6: stopping the scheduling daemons..."
    local cron_svc at_svc
    cron_svc="$(detect_cron_service)"
    at_svc="$(detect_at_service)"
    systemctl stop "${cron_svc}.service" >/dev/null 2>&1 || true
    systemctl mask "${cron_svc}.service" >/dev/null 2>&1 || true
    systemctl stop "${at_svc}.service"   >/dev/null 2>&1 || true
    systemctl disable "${at_svc}.service" >/dev/null 2>&1 || true
    printf '%s\n' "$cron_svc" > "$BACKUP_DIR/cron-service-name"
    printf '%s\n' "$at_svc"   > "$BACKUP_DIR/at-service-name"
}

# ---------------------------------------------------------------------------
# The briefing the student reads
# ---------------------------------------------------------------------------

print_briefing() {
    local cron_svc at_svc
    cron_svc="$(cat "$BACKUP_DIR/cron-service-name" 2>/dev/null || echo cron)"
    at_svc="$(cat "$BACKUP_DIR/at-service-name" 2>/dev/null || echo atd)"

cat <<BRIEF

================================================================================
