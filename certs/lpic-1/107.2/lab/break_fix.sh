#   S O L U T I O N   —   S T O P   R E A D I N G   I F   Y O U   H A V E
#   N O T   T R I E D   Y E T
#
# ============================================================================
#
# ---------------------------------------------------------------------------
# STEP 0 — Triage: is the scheduler even alive?
# ---------------------------------------------------------------------------
#
#   Before reading a single crontab, confirm the daemons. A perfect crontab on
#   a dead daemon produces exactly the same symptom as a broken crontab.
#
#     # systemctl status cron    # Debian/Ubuntu
#     # systemctl status crond   # RHEL/Fedora/SUSE
#     ● cron.service
#          Loaded: masked (Reason: Unit cron.service is masked.)
#          Active: inactive (dead)
#
#   'masked' is not 'disabled'. A masked unit is symlinked to /dev/null and
#   CANNOT be started until it is unmasked — this is why 'systemctl start'
#   returns "Unit is masked" instead of just working.
#
#     # systemctl unmask cron
#     Removed /etc/systemd/system/cron.service.
#     # systemctl enable --now cron
#     # systemctl is-active cron
#     active
#
#     # systemctl enable --now atd
#     # systemctl is-active atd
#     active
#
#   Objective A is now met. Confirm with:
#     # systemctl list-unit-files | grep -E '^(cron|crond|atd)\.service'
#     cron.service     enabled  enabled
#     atd.service      enabled  enabled
#
# ---------------------------------------------------------------------------
# STEP 1 — Access control: cron.allow / cron.deny and at.allow / at.deny
# ---------------------------------------------------------------------------
#
#   Symptom:
#     # su - billing -c 'crontab -l'
#     You (billing) are not allowed to use this program (crontab)
#
#   The rule, from crontab(1) and cron(8):
#
#     * If /etc/cron.allow EXISTS, it is authoritative: only users listed in
#       it may use crontab. /etc/cron.deny is then IGNORED ENTIRELY.
#     * If cron.allow does NOT exist, cron.deny is consulted: everyone except
#       the users listed there may use crontab.
#     * If NEITHER file exists, behaviour is distribution-dependent — on
#       Debian all users may use cron; on some builds only root may.
#     * root is always allowed regardless.
#
#     The at(1) pair works identically: at.allow wins over at.deny, and if
#     neither exists, only root may use at.
#
#   Inspect:
#     # ls -l /etc/cron.allow /etc/cron.deny /etc/at.allow /etc/at.deny
#     -rw------- 1 root root 20 ... /etc/cron.allow
#     ls: cannot access '/etc/cron.deny': No such file or directory
#     ls: cannot access '/etc/at.allow': No such file or directory
#     -rw-r----- 1 root daemon 12 ... /etc/at.deny
#
#     # cat /etc/cron.allow
#     root
#     operations
#
#   The billing user is missing from the allow-list, and is explicitly present
#   in at.deny. The correct fix is NOT to delete the allow-list (that changes
#   the policy of the whole machine); it is to add the one account that is
#   supposed to be there, and to remove the one wrong deny entry:
#
#     # printf 'billing\n' >> /etc/cron.allow
#     # chmod 0600 /etc/cron.allow
#     # sed -i '/^billing$/d' /etc/at.deny
#
#   Verify:
#     # su - billing -c 'crontab -l' >/dev/null && echo OK
#     OK
#     # su - billing -c 'echo /bin/true | at now + 1 minute'
#     warning: commands will be executed using /bin/sh
#     job 1 at Thu Aug 27 12:34:00 2026
#     # atq
#     1       Thu Aug 27 12:34:00 2026 a billing
#
#   (Inspect the queued job's saved environment with 'at -c 1'; remove it with
#   'atrm 1'. Note that at snapshots your entire environment at submit time —
#   the opposite of cron's behaviour, and a favourite exam distinction.)
#
#   Objective B met.
#
# ---------------------------------------------------------------------------
# STEP 2 — The user crontab: field count, '%', and the DOM/DOW trap
# ---------------------------------------------------------------------------
#
#     # crontab -l -u billing
#     # Billing pipeline — per-user crontab
#     MAILTO=""
#     */2 * * * * billing /usr/local/bin/billing-report.sh
#     0 6 1 * 1 /usr/bin/date +%Y-%m-%d >> /var/log/billing-report/stamp.log
#
#   Three defects:
#
#   (a) SIX time-ish fields in a USER crontab. Format, per crontab(5):
#
#         user crontab:    m h dom mon dow  COMMAND
#         system crontab:  m h dom mon dow  USER  COMMAND
#                          (/etc/crontab and /etc/cron.d/* only)
#
#       Here 'billing' is being taken as the first word of the command, so
#       cron tries to execute a program literally named 'billing'. In the log:
#
#         # journalctl -u cron --since '-10 min' | tail -3
#         CRON[1841]: (billing) CMD (billing /usr/local/bin/billing-report.sh)
#         CRON[1840]: (CRON) info (No MTA installed, discarding output)
#
#       That "No MTA" line is the second lesson: cron mails stdout/stderr to
#       the job owner, and with no mail transport the evidence is discarded.
#       Set MAILTO to a real address, or redirect the job's output to a file,
#       or you are debugging blind.
#
#       Fix: drop the user field.
#
#         */2 * * * * /usr/local/bin/billing-report.sh
#
#   (b) The '%' in '/usr/bin/date +%Y-%m-%d'. In crontab(5), an unescaped '%'
#       is translated to a NEWLINE, and everything after the first '%' becomes
#       standard input to the command. So cron actually runs:
#
#         /usr/bin/date +
#       with stdin:
#         Y-m-d >> /var/log/billing-report/stamp.log
#
#       ...which is why the redirect never happens and 'date' errors out. Each
#       '%' must be escaped with a backslash:
#
#         0 6 1 * 1 /usr/bin/date +\%Y-\%m-\%d >> /var/log/billing-report/stamp.log
#
#       (In a system crontab or a cron.d fragment the same rule applies. The
#       robust habit is to put anything non-trivial in a script and call the
#       script — a crontab line is not a shell script.)
#
#   (c) The day-of-month / day-of-week OR. From crontab(5):
#
#         "Note: The day of a command's execution can be specified in the
#          following two fields — day of month, and day of week. If both
#          fields are restricted (i.e. are not *), the command will be run
#          when EITHER field matches the current time."
#
#       So '0 6 1 * 1' means 06:00 on the 1st of every month, AND ALSO 06:00
#       every Monday — not the intersection. To get "the 1st, only if it is a
#       Monday" you must test inside the command:
#
#         0 6 1 * *  [ "$(date +\%u)" -eq 1 ] && /usr/local/bin/month-start.sh
#
#   Install the corrected crontab the supported way — never by editing the
#   spool file directly, because 'crontab -e'/'crontab <file>' is what triggers
#   cron to re-read it and what runs the syntax check:
#
#     # crontab -u billing - <<'EOF'
#     MAILTO=root
#     */2 * * * * /usr/local/bin/billing-report.sh
#     0 6 1 * *  [ "$(date +\%u)" -eq 1 ] && /usr/bin/date +\%Y-\%m-\%d >> /var/log/billing-report/stamp.log
#     EOF
#     # crontab -l -u billing
#
# ---------------------------------------------------------------------------
# STEP 3 — Permissions and the cron environment
# ---------------------------------------------------------------------------
#
#     # ls -l /usr/local/bin/billing-report.sh
#     -rw-r--r-- 1 root root 214 ... /usr/local/bin/billing-report.sh
#
#   No execute bit. cron invokes the command through /bin/sh -c, so this gives
#   "Permission denied" in the mail/log, not a shell error you can see.
#
#     # chmod 0755 /usr/local/bin/billing-report.sh
#
#   Now run it as the billing user, non-interactively, which is the closest
#   cheap approximation of what cron does:
#
#     # su billing -s /bin/sh -c '/usr/local/bin/billing-report.sh'
#     /usr/local/bin/billing-report.sh: line 4: BILLING_HOME: unbound variable
#
#   The script depends on /etc/profile.d/billing.sh. cron does NOT run a login
#   shell and does NOT source /etc/profile, ~/.profile or ~/.bashrc. What cron
#   actually provides (crontab(5)) is essentially:
#
#     SHELL=/bin/sh
#     PATH=/usr/bin:/bin          (short! not your interactive PATH)
#     LOGNAME, HOME               (from /etc/passwd)
#     MAILTO                      (if set in the crontab)
#
#   plus whatever VAR=value assignments appear in the crontab itself. Prove it
#   to yourself with a throwaway job:
#
#     * * * * * env > /tmp/cron-env.txt
#     # diff <(sort /tmp/cron-env.txt) <(env | sort)
#
#   There are three legitimate fixes, in descending order of preference:
#
#     1. Make the script self-sufficient — the correct production answer.
#          #!/bin/bash
#          set -euo pipefail
#          export PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin:/opt/billing/bin
#          BILLING_HOME="${BILLING_HOME:-/var/log/billing-report}"
#          /opt/billing/bin/billing-helper >> "$BILLING_HOME/report.log"
#
#        Absolute paths for every binary, and defaults for every variable.
#
#     2. Set the variables in the crontab itself. crontab(5) allows
#        assignments before the job lines; they are NOT shell, so no quotes
#        are expanded and no other variables are interpolated:
#          PATH=/usr/local/bin:/usr/bin:/bin:/opt/billing/bin
#          BILLING_HOME=/var/log/billing-report
#          */2 * * * * /usr/local/bin/billing-report.sh
#
#     3. Source the profile explicitly from the job line — works, but couples
#        a batch job to interactive login configuration; use only when you
#        cannot change the script:
#          */2 * * * * . /etc/profile.d/billing.sh; /usr/local/bin/billing-report.sh
#
#   Apply fix 1, then confirm the directory is writable by the job's user:
#
#     # install -d -o billing -g billing -m 0755 /var/log/billing-report
#     # su billing -s /bin/sh -c '/usr/local/bin/billing-report.sh' && tail -1 /var/log/billing-report/report.log
#     2026-08-27T12:40:01+00:00 billing report generated by billing
#
#   Wait two minutes and confirm cron itself is doing it:
#
#     # sleep 130; tail -2 /var/log/billing-report/report.log
#     # journalctl -u cron --since '-5 min' | grep billing
#     CRON[2210]: (billing) CMD (/usr/local/bin/billing-report.sh)
#
#   Objective C met.
#
# ---------------------------------------------------------------------------
# STEP 4 — /etc/cron.d: file name, permissions, trailing newline, USER field
# ---------------------------------------------------------------------------
#
#     # ls -l /etc/cron.d/
#     -rw-rw-rw- 1 root root 133 ... billing-report.bak
#
#   Three separate reasons this file is inert:
#
#   (a) THE NAME. Files in /etc/cron.d are processed with run-parts naming
#       rules: the name must consist only of upper/lower case letters, digits,
#       underscores and hyphens. A '.' anywhere in the name — '.bak', '.conf',
#       '.disabled' — makes the file INVISIBLE to cron. This is why renaming a
#       cron.d file to 'foo.bak' is the standard way to disable it, and why
#       'foo.conf' silently never runs. Verify the rule on your distro with:
#
#         # run-parts --test /etc/cron.d
#         (the .bak file is absent from the output)
#
#   (b) THE PERMISSIONS. cron refuses any file in /etc/cron.d (and /etc/crontab
#       itself) that is writable by group or other, and logs it:
#
#         # journalctl -u cron | grep -i cron.d
#         cron[701]: (*system*) INSECURE MODE (mode 0600 expected) (/etc/cron.d/...)
#
#       Required: owned by root, mode 0644 (some builds accept 0600).
#
#   (c) THE MISSING TRAILING NEWLINE. A crontab file must end with a newline;
#       cron may silently drop the final line otherwise. Check with:
#
#         # tail -c 1 /etc/cron.d/billing-report | xxd
#         00000000: 0a                                       .
#
#   And the structural point Objective D asks about: /etc/cron.d files and
#   /etc/crontab are SYSTEM crontabs, so they have SIX fields before the
#   command — the sixth is the USER to run as. That is the exact opposite of
#   Step 2(a): the user field is REQUIRED here and FORBIDDEN there. Getting
#   this backwards is the single most common cron mistake there is.
#
#   Fix:
#     # mv /etc/cron.d/billing-report.bak /etc/cron.d/billing-report
#     # chown root:root /etc/cron.d/billing-report
#     # chmod 0644 /etc/cron.d/billing-report
#     # printf '\n' >> /etc/cron.d/billing-report      # ensure trailing newline
#     # cat /etc/cron.d/billing-report
#     SHELL=/bin/bash
#     PATH=/usr/local/sbin:/usr/local/bin:/sbin:/bin:/usr/sbin:/usr/bin
#     */5 * * * *  root  /usr/local/bin/billing-report.sh
#
#   cron re-reads /etc/cron.d automatically (it stats the directory every
#   minute); no restart is needed, and restarting to "make it pick up" is a
#   habit worth unlearning. Confirm:
#
#     # journalctl -u cron --since '-6 min' | grep 'CMD'
#     CRON[2402]: (root) CMD (/usr/local/bin/billing-report.sh)
#
#   Objective D met.
#
# ---------------------------------------------------------------------------
# STEP 5 — /etc/cron.daily and anacron
# ---------------------------------------------------------------------------
#
#     # ls -l /etc/cron.daily/billing-rotate
#     -rw-r--r-- 1 root root 138 ... /etc/cron.daily/billing-rotate
#
#   /etc/cron.{hourly,daily,weekly,monthly} are executed by run-parts, which
#   runs only files that are EXECUTABLE and whose names pass the same naming
#   rule as Step 4(a). No execute bit means the job simply never runs, with no
#   error anywhere.
#
#     # chmod 0755 /etc/cron.daily/billing-rotate
#     # run-parts --test /etc/cron.daily
#     /etc/cron.daily/billing-rotate
#     ...
#
#   '--test' prints what WOULD run without running it — that is the way to
#   demonstrate Objective E, rather than executing the script by hand (calling
#   it directly proves the script works, not that the system will call it).
#
#   Now the anacron side. anacron exists for machines that are not on 24/7: it
#   works in DAYS, not clock times, and runs a job if the recorded timestamp is
#   older than the period.
#
#     # cat /etc/anacrontab
#     SHELL=/bin/sh
#     PATH=/usr/local/sbin:/usr/local/bin:/sbin:/bin:/usr/sbin:/usr/bin
#     RANDOM_DELAY=45
#     START_HOURS_RANGE=3-4
#     # period  delay  job-identifier  command
#     1         5      cron.daily      run-parts --report /etc/cron.daily
#     7         25     cron.weekly     run-parts --report /etc/cron.weekly
#     @monthly  45     cron.monthly    run-parts --report /etc/cron.monthly
#
#   Fields, per anacrontab(5): PERIOD in days (or @daily/@weekly/@monthly),
#   DELAY in minutes after anacron starts, a JOB-ID used as the timestamp file
#   name, and the command. START_HOURS_RANGE bounds the hours during which
#   jobs may start; RANDOM_DELAY adds jitter so a fleet does not stampede.
#
#   The timestamps live in /var/spool/anacron/, one file per job-id, each
#   containing the YYYYMMDD of the last successful run:
#
#     # cat /var/spool/anacron/cron.daily
#     20260827
#
#   Because that is today's date, anacron considers cron.daily already done.
#   To force a run now, ignoring both the timestamp and the hours range:
#
#     # anacron -f -n -d cron.daily
#         -f  force: ignore the timestamps
#         -n  now: ignore the delay
#         -d  foreground, log to stderr instead of syslog
#
#   Or reset the timestamp so the normal schedule picks it up:
#     # date -d yesterday +%Y%m%d > /var/spool/anacron/cron.daily
#
#   (Restore START_HOURS_RANGE to your distribution's default if you widened
#   it; the lab narrowed it to 3-4 to keep the job from firing mid-session.)
#
#   Objective E met.
#
# ---------------------------------------------------------------------------
# STEP 6 — The systemd timer
# ---------------------------------------------------------------------------
#
#     # systemctl list-timers --all | grep billing
#     (nothing — the timer is disabled AND stopped)
#
#     # systemctl status billing-metrics.timer
#     ● billing-metrics.timer - Collect billing metrics every 3 minutes
#          Loaded: loaded (/etc/systemd/system/billing-metrics.timer; disabled)
#          Active: inactive (dead)
#
#     # systemctl start billing-metrics.timer
#     Failed to start billing-metrics.timer: Unit billing-metric.service not found.
#
#   Two faults:
#
#   (a) 'Unit=billing-metric.service' — singular, and no such unit exists. The
#       Unit= directive names the service the timer activates; when omitted it
#       defaults to the same base name as the timer with a .service suffix.
#       The typo is why the timer will not even start.
#
#   (b) 'OnCalendar=*-*-* *:*:00/3'. This is a SECONDS expression: it means
#       "every third second starting at second 0, of every minute" — not every
#       three minutes. Never guess at a calendar expression; systemd ships a
#       validator, and using it is the point of Objective F:
#
#         # systemd-analyze calendar '*-*-* *:*:00/3'
#         Original form: *-*-* *:*:00/3
#         Normalized form: *-*-* *:*:00/3
#            Next elapse: Thu 2026-08-27 12:45:03 UTC
#               (in UTC): Thu 2026-08-27 12:45:03 UTC
#               From now: 1s left
#
#         # systemd-analyze calendar --iterations=4 '*:0/3'
#         Original form: *:0/3
#         Normalized form: *-*-* *:00/3:00
#            Next elapse: Thu 2026-08-27 12:48:00 UTC
#               From now: 2min 14s left
#            Iter. #2: Thu 2026-08-27 12:51:00 UTC
#            Iter. #3: Thu 2026-08-27 12:54:00 UTC
#            Iter. #4: Thu 2026-08-27 12:57:00 UTC
#
#       '*:0/3' — every third MINUTE from minute 0 — is what was intended.
#       ('OnUnitActiveSec=3min' is the other correct answer, and a different
#       thing: monotonic, relative to the last activation, rather than wall
#       clock. Use OnCalendar when the wall-clock instant matters, monotonic
#       timers when the interval between runs matters.)
#
#   Fix the unit:
#     # cat /etc/systemd/system/billing-metrics.timer
#     [Unit]
#     Description=Collect billing metrics every 3 minutes
#
#     [Timer]
#     OnCalendar=*:0/3
#     Persistent=true
#     Unit=billing-metrics.service
#
#     [Install]
#     WantedBy=timers.target
#
#   Then — and this order matters — reload, enable, start, verify:
#
#     # systemd-analyze verify /etc/systemd/system/billing-metrics.timer
#     # systemctl daemon-reload
#     # systemctl enable --now billing-metrics.timer
#     Created symlink /etc/systemd/system/timers.target.wants/billing-metrics.timer → ...
#     # systemctl list-timers billing-metrics.timer
#     NEXT                        LEFT     LAST  PASSED  UNIT                   ACTIVATES
#     Thu 2026-08-27 12:48:00 UTC 2min 9s  -     -       billing-metrics.timer  billing-metrics.service
#
#     # sleep 200; cat /var/lib/billing-metrics.txt
#     2026-08-27T12:48:00+00:00 metrics collected
#     # systemctl status billing-metrics.service
#          Active: inactive (dead) since ...   <-- correct for Type=oneshot
#     # journalctl -u billing-metrics.service --since '-10 min'
#
#   Note 'Persistent=true': if the machine was off when the timer should have
#   fired, systemd runs it once immediately at next boot — the systemd
#   equivalent of what anacron does for cron. Timestamps for that live under
#   /var/lib/systemd/timers/.
#
#   Objective F met.
#
# ---------------------------------------------------------------------------
# STEP 7 — Objective G: the three one-sentence answers
# ---------------------------------------------------------------------------
#
#   * '0 6 1 * 1' does not mean "the 1st when it is a Monday" because when
#     BOTH day-of-month and day-of-week are restricted, cron ORs them — it
#     runs on the 1st of the month AND on every Monday — so an AND has to be
#     expressed as a test inside the command with dom or dow left as '*'.
#
#   * A bare '%' in a crontab command is not passed to the shell: crontab(5)
#     turns the first '%' into a newline and feeds everything after it to the
#     command on standard input, so 'date +%Y' runs as 'date +' with 'Y' as
#     stdin — it must be written '\%'.
#
#   * The script worked in your shell and not under cron because cron starts
#     the job with a minimal, non-login environment (SHELL=/bin/sh,
#     PATH=/usr/bin:/bin, HOME and LOGNAME from /etc/passwd) and never sources
#     /etc/profile, /etc/profile.d/*, ~/.profile or ~/.bashrc, so anything
#     your interactive login exported simply is not there.
#
