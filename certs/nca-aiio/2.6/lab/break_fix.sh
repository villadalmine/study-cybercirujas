#!/usr/bin/env bash
# =============================================================================
# NCA-AIIO 2.6 - Identify facility requirements - Break & Fix lab
#
# lab-resources: cpus=1 ram_mb=256
#
# Scenario
#   You are the infrastructure lead for an AI cluster of 8x NVIDIA DGX H100
#   systems. A colleague wrote the rack plan (rack-plan.conf) without reading
#   the site survey (site-survey.conf). The facility check now fails on power,
#   power redundancy and cooling. Fix the plan so the facility can host the
#   cluster, without changing the facility and without removing systems.
#
# What this lab teaches
#   - A DGX H100 draws about 10.2 kW at maximum load and occupies 8U.
#     Plan for maximum power, not typical power.
#   - Rack power budget: the derated PDU capacity per feed. With A/B (2N)
#     feeds, EACH feed must carry the WHOLE rack load if the other one fails.
#   - Cooling budget: the heat a rack can reject (air-cooled limit per rack).
#     Every watt in is a watt of heat out.
#   - Rack units, available rack positions, and the fact that density limits
#     usually come from power and cooling before space runs out.
#
# Official sources
#   https://docs.nvidia.com/dgx/dgxh100-user-guide/introduction-to-dgxh100.html#dgx-h100-component-descriptions
#   https://docs.nvidia.com/dgx-superpod/reference-architecture-scalable-infrastructure-b200/latest/index.html
#   https://dam-cdn.nvd.orangelogic.com/AssetLink/x874j05hy3m3r2sor84kpvp70750m468.pdf
#   https://academy.nvidia.com/en/course/ai-infrastructure-operations-fundamentals/?cm=64727
#
# Usage
#   ./lab.sh            same as "break"
#   ./lab.sh break      prepare the lab and break it (idempotent: resets it)
#   ./lab.sh verify     exit 0 only when the plan is fixed
#   ./lab.sh cleanup    remove everything this lab created
#
# Safety
#   This lab only writes text files under its own directory (and one symlink
#   in /usr/local/bin when run as root). It touches no services, no network,
#   no kernel settings. It is safe on any disposable VM.
# =============================================================================
set -euo pipefail

if [[ ${EUID:-$(id -u)} -eq 0 ]]; then
    LAB_DIR="${LAB_DIR:-/opt/facility-lab}"
    LINK="/usr/local/bin/facility-check"
else
    LAB_DIR="${LAB_DIR:-$HOME/facility-lab}"
    LINK=""
fi

SURVEY="$LAB_DIR/site-survey.conf"
PLAN="$LAB_DIR/rack-plan.conf"
CHECKER="$LAB_DIR/bin/facility-check"
STATE="$LAB_DIR/.state"

say()  { printf '%s\n' "$*"; }
hr()   { say "--------------------------------------------------------------------------"; }

# Read KEY=value from a config file without executing it.
get() {
    local file="$1" key="$2"
    grep -E "^[[:space:]]*${key}[[:space:]]*=" "$file" 2>/dev/null \
        | tail -n1 | cut -d= -f2- | sed -e 's/#.*//' -e 's/["[:space:]]//g'
}

is_num() { [[ "${1:-}" =~ ^[0-9]+([.][0-9]+)?$ ]]; }

write_survey() {
    cat > "$SURVEY" <<'EOF'
# =====================================================================
# SITE SURVEY - Data hall B, row 3            (facility team, read-only)
# These are physical properties of the building. Do NOT edit this file:
# the PDUs, the chillers and the floor will not change because you did.
# =====================================================================

# Rack positions available to this project in row 3
AVAILABLE_RACKS=6

# Usable height per rack, and height reserved for top-of-rack
# switches, management switch, PDUs and cable management
RACK_U=42
RESERVED_U=6

# Power: each rack can receive at most two independent feeds (A and B),
# fed from different UPS/PDU paths. Each feed is a 415 V 3-phase 60 A
# circuit: 415 * 60 * sqrt(3) = ~43.1 kVA, derated to 80% continuous
# load = 34.5 kW usable per feed.
MAX_FEEDS_PER_RACK=2
FEED_KW_USABLE=34.5

# Redundancy policy for production AI racks: 2N (A+B).
# If one feed is lost, the remaining feed must carry the whole rack.
REDUNDANCY_POLICY=2N

# Cooling: row 3 is air-cooled (rear-door heat exchangers are not
# installed). Maximum heat each rack position can reject:
AIR_COOLING_KW_PER_RACK=25
EOF
}

write_broken_plan() {
    cat > "$PLAN" <<'EOF'
# =====================================================================
# RACK PLAN - AI training cluster "atlas"          (owned by: you)
# =====================================================================

# Compute requirement from the project: this number is fixed.
REQUIRED_SYSTEMS=8

# System model and its data sheet values (DGX H100 user guide)
SYSTEM_MODEL=dgx-h100
SYSTEM_MAX_KW=10.2
SYSTEM_RU=8

# Layout chosen by the previous planner ("fewer racks = cheaper")
RACKS=2
SYSTEMS_PER_RACK=4

# Power feeds per rack (1 = single feed, 2 = A+B)
FEEDS_PER_RACK=1
EOF
}

write_checker() {
    mkdir -p "$LAB_DIR/bin"
    cat > "$CHECKER" <<'CHECKER_EOF'
#!/usr/bin/env bash
# facility-check: validates rack-plan.conf against site-survey.conf
set -uo pipefail
DIR="$(cd "$(dirname "$(readlink -f "$0")")/.." && pwd)"
SURVEY="$DIR/site-survey.conf"
PLAN="$DIR/rack-plan.conf"
get() {
    grep -E "^[[:space:]]*$2[[:space:]]*=" "$1" 2>/dev/null \
        | tail -n1 | cut -d= -f2- | sed -e 's/#.*//' -e 's/["[:space:]]//g'
}
fail=0
ok()  { printf '  [ OK ]  %s\n' "$*"; }
bad() { printf '  [FAIL]  %s\n' "$*"; fail=1; }

req=$(get "$PLAN" REQUIRED_SYSTEMS); kw=$(get "$PLAN" SYSTEM_MAX_KW)
ru=$(get "$PLAN" SYSTEM_RU);         racks=$(get "$PLAN" RACKS)
spr=$(get "$PLAN" SYSTEMS_PER_RACK); feeds=$(get "$PLAN" FEEDS_PER_RACK)
avail=$(get "$SURVEY" AVAILABLE_RACKS); rack_u=$(get "$SURVEY" RACK_U)
res_u=$(get "$SURVEY" RESERVED_U);     maxf=$(get "$SURVEY" MAX_FEEDS_PER_RACK)
feed_kw=$(get "$SURVEY" FEED_KW_USABLE); cool=$(get "$SURVEY" AIR_COOLING_KW_PER_RACK)

for v in req kw ru racks spr feeds avail rack_u res_u maxf feed_kw cool; do
    if ! [[ "${!v}" =~ ^[0-9]+([.][0-9]+)?$ ]]; then
        echo "facility-check: value '$v' is missing or not a number"; exit 2
    fi
done

load=$(awk -v s="$spr" -v k="$kw" 'BEGIN{printf "%.1f", s*k}')
total=$(( racks * spr ))
used_u=$(( spr * ru )); free_u=$(( rack_u - res_u ))
# Capacity that survives a single feed failure:
#   2 feeds -> one feed must carry everything -> feed_kw
#   1 feed  -> no redundancy at all
surv=$feed_kw

echo "facility-check: plan=$PLAN"
echo "  per-rack load at max power: $spr x $kw kW = $load kW"
echo

if (( total >= req )); then ok "capacity: $total systems planned (required $req)"
else bad "capacity: $total systems planned, project requires $req"; fi

if (( racks <= avail )); then ok "rack positions: $racks used of $avail available"
else bad "rack positions: $racks needed, only $avail available in the row"; fi

if (( used_u <= free_u )); then ok "space: ${used_u}U of ${free_u}U usable per rack"
else bad "space: ${used_u}U needed, only ${free_u}U usable per rack"; fi

if (( feeds > maxf )); then
    bad "power feeds: $feeds requested, the rack position supports $maxf"
elif (( feeds < 2 )); then
    bad "redundancy: single feed per rack, policy is 2N (A+B) -> one PDU/UPS fault drops the whole rack"
else
    ok "redundancy: $feeds feeds (A+B)"
fi

if awk -v l="$load" -v c="$surv" 'BEGIN{exit !(l<=c)}'; then
    ok "power: $load kW per rack fits on one feed ($surv kW usable), survives a feed loss"
else
    bad "power: $load kW per rack exceeds $surv kW usable per feed -> breaker trip at full load / no failover headroom"
fi

if awk -v l="$load" -v c="$cool" 'BEGIN{exit !(l<=c)}'; then
    ok "cooling: $load kW of heat per rack, air limit $cool kW"
else
    bad "cooling: $load kW of heat per rack exceeds air-cooling limit of $cool kW -> inlet temp rises, GPUs throttle"
fi

echo
if (( fail == 0 )); then echo "RESULT: PASS - the facility can host this plan"; exit 0
else echo "RESULT: FAIL - the facility cannot host this plan"; exit 1; fi
CHECKER_EOF
    chmod 0755 "$CHECKER"
}

do_break() {
    mkdir -p "$LAB_DIR"
    # Reset to a known state every time (idempotent)
    [[ -f "$SURVEY" ]] && chmod u+w "$SURVEY" 2>/dev/null || true
    write_survey
    write_broken_plan
    write_checker
    chmod 0444 "$SURVEY"
    sha256sum "$SURVEY" | awk '{print $1}' > "$STATE"
    chmod 0444 "$STATE"
    if [[ -n "$LINK" ]]; then
        ln -sfn "$CHECKER" "$LINK"
        CMD="facility-check"
    else
        CMD="$CHECKER"
    fi

    hr
    say "LAB READY - NCA-AIIO 2.6 Identify facility requirements"
    hr
    say "Files:"
    say "  $SURVEY   (facility facts, read-only)"
    say "  $PLAN     (your rack plan, editable)"
    say
    say "SYMPTOM - run:  $CMD"
    say
    "$CHECKER" || true
    say
    say "GOAL"
    say "  Edit ONLY rack-plan.conf so that facility-check reports PASS:"
    say "   - still at least 8 DGX H100 systems (REQUIRED_SYSTEMS stays 8)"
    say "   - honest data sheet values (SYSTEM_MAX_KW=10.2, SYSTEM_RU=8)"
    say "   - 2N power: the rack must survive the loss of one feed"
    say "   - heat per rack within the air-cooling limit of the row"
    say "   - no more racks than the row has available"
    say "  Do not edit site-survey.conf: the building does not change."
    say
    say "Check your work with:  $0 verify"
    hr
}

do_verify() {
    local errs=0
    v_fail() { say "  [FAIL] $*"; errs=$((errs+1)); }

    if [[ ! -f "$PLAN" || ! -f "$SURVEY" || ! -f "$STATE" ]]; then
        say "Lab not prepared. Run: $0 break"; return 1
    fi

    # The facility must be untouched
    if [[ "$(sha256sum "$SURVEY" | awk '{print $1}')" != "$(cat "$STATE")" ]]; then
        v_fail "site-survey.conf was modified: fix the plan, not the building (run '$0 break' to reset)"
    fi

    local req kw ru racks spr feeds
    req=$(get "$PLAN" REQUIRED_SYSTEMS); kw=$(get "$PLAN" SYSTEM_MAX_KW)
    ru=$(get "$PLAN" SYSTEM_RU);         racks=$(get "$PLAN" RACKS)
    spr=$(get "$PLAN" SYSTEMS_PER_RACK); feeds=$(get "$PLAN" FEEDS_PER_RACK)
    for v in req kw ru racks spr feeds; do
        is_num "${!v}" || { v_fail "$v is missing or not a number in rack-plan.conf"; say "NOT FIXED"; return 1; }
    done

    # Data sheet values and requirement must stay honest
    [[ "$req" == "8" ]] || v_fail "REQUIRED_SYSTEMS must stay 8 (it is the project requirement)"
    awk -v k="$kw" 'BEGIN{exit !(k>=10.2)}' || v_fail "SYSTEM_MAX_KW must be 10.2 (DGX H100 max power); plan for max, not typical"
    [[ "$ru" == "8" ]] || v_fail "SYSTEM_RU must be 8 (DGX H100 is 8U)"
    [[ "$spr" =~ ^[0-9]+$ && "$racks" =~ ^[0-9]+$ && "$feeds" =~ ^[0-9]+$ ]] \
        || v_fail "RACKS, SYSTEMS_PER_RACK and FEEDS_PER_RACK must be integers"

    if (( errs == 0 )); then
        # Independent evaluation (does not trust the checker script)
        local avail rack_u res_u maxf feed_kw cool load
        avail=$(get "$SURVEY" AVAILABLE_RACKS); rack_u=$(get "$SURVEY" RACK_U)
        res_u=$(get "$SURVEY" RESERVED_U);     maxf=$(get "$SURVEY" MAX_FEEDS_PER_RACK)
        feed_kw=$(get "$SURVEY" FEED_KW_USABLE); cool=$(get "$SURVEY" AIR_COOLING_KW_PER_RACK)
        load=$(awk -v s="$spr" 'BEGIN{printf "%.1f", s*10.2}')

        (( spr >= 1 ))                     || v_fail "SYSTEMS_PER_RACK must be at least 1"
        (( racks * spr >= 8 ))             || v_fail "only $((racks*spr)) systems planned, 8 required"
        (( racks <= avail ))               || v_fail "$racks racks needed, only $avail available"
        (( spr * 8 <= rack_u - res_u ))    || v_fail "rack space exceeded"
        (( feeds == 2 && feeds <= maxf ))  || v_fail "FEEDS_PER_RACK must be 2 (A+B) for 2N redundancy"
        awk -v l="$load" -v c="$feed_kw" 'BEGIN{exit !(l<=c)}' \
            || v_fail "$load kW per rack does not fit on one surviving feed ($feed_kw kW)"
        awk -v l="$load" -v c="$cool" 'BEGIN{exit !(l<=c)}' \
            || v_fail "$load kW per rack exceeds the air-cooling limit ($cool kW)"
    fi

    if (( errs == 0 )); then
        say "FIXED: $racks racks x $spr DGX H100, 2N power, within power and cooling budgets."
        return 0
    fi
    say "NOT FIXED ($errs problem(s)). Run facility-check for details."
    return 1
}

do_cleanup() {
    if [[ -n "$LINK" && -L "$LINK" ]]; then
        rm -f "$LINK"
    fi
    if [[ -d "$LAB_DIR" ]]; then
        chmod -R u+w "$LAB_DIR" 2>/dev/null || true
        rm -rf "$LAB_DIR"
    fi
    say "Cleanup done: $LAB_DIR removed."
}

case "${1:-break}" in
    break)   do_break ;;
    verify)  do_verify ;;
    cleanup) do_cleanup ;;
    *)       say "Usage: $0 [break|verify|cleanup]"; exit 2 ;;
esac

# =============================================================================
# SOLUTION (step by step)
# =============================================================================
# 1. Read the symptom:
#      facility-check        (or ~/facility-lab/bin/facility-check as non-root)
#    It reports three failures for 2 racks x 4 DGX H100:
#      - redundancy: one feed per rack, policy is 2N
#      - power: 4 x 10.2 = 40.8 kW per rack > 34.5 kW usable per feed
#      - cooling: 40.8 kW of heat > 25 kW air-cooling limit per rack
#    Space (4 x 8U = 32U of 36U) and rack count (2 of 6) were fine: in AI
#    data centers density is limited by power and cooling long before space.
#
# 2. Read the facility facts in site-survey.conf and derive the per-rack limit:
#      2N power  -> the rack must run on ONE feed  -> max 34.5 kW
#      cooling   -> max 25 kW of heat per rack
#      effective per-rack limit = min(34.5, 25) = 25 kW
#
# 3. Systems per rack = floor(25 / 10.2) = 2   (2 x 10.2 = 20.4 kW)
#    Space check: 2 x 8U = 16U <= 36U usable. OK.
#
# 4. Racks needed = ceil(8 / 2) = 4   -> 4 <= 6 available. OK.
#
# 5. Edit rack-plan.conf:
#      RACKS=4
#      SYSTEMS_PER_RACK=2
#      FEEDS_PER_RACK=2
#    e.g.:
#      sed -i -e 's/^RACKS=.*/RACKS=4/' \
#             -e 's/^SYSTEMS_PER_RACK=.*/SYSTEMS_PER_RACK=2/' \
#             -e 's/^FEEDS_PER_RACK=.*/FEEDS_PER_RACK=2/' /opt/facility-lab/rack-plan.conf
#
# 6. Confirm:
#      facility-check      -> RESULT: PASS
#      ./lab.sh verify     -> FIXED ... (exit 0)
#
# Takeaways for the exam
#   - Size power from the system's MAXIMUM power (DGX H100 ~10.2 kW), not average.
#   - With A/B feeds, each feed must carry the full rack load on its own.
#   - Derate circuits (80% continuous) before counting usable kW.
#   - Every kW of IT power becomes a kW of heat: air cooling caps rack density;
#     denser racks (e.g. DGX B200 / GB200 class) push toward liquid cooling,
#     as described in the DGX SuperPOD reference architectures.
#   - Wrong answers that verify rejects: editing the survey, lowering
#     SYSTEM_MAX_KW to a "typical" value, or dropping below 8 systems.
#
# 7. When finished:
#      ./lab.sh cleanup
# =============================================================================