#!/usr/bin/env python3
"""Regenerate the certification table in README.md from docs/STATUS.md.

docs/STATUS.md is itself derived from disk (scripts/status_matrix.py, checked by
`status_matrix.py --check`), so the table a visitor sees on the front page is
two projections away from the files and never a hand-kept list. A language
counts as available only when docs/STATUS.md marks it complete (✅): every topic,
above the quality floor.

    scripts/gen_readme_table.py            # rewrite the block
    scripts/gen_readme_table.py --check    # fail if it is stale (make verify, CI)

Free: reads two files, calls no network, spends no quota.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
DOC = REPO / "README.md"
STATUS = REPO / "docs/STATUS.md"
CATALOG = REPO / "catalog.yaml"
START = "<!-- CERT-TABLE:START -->"
END = "<!-- CERT-TABLE:END -->"
LANG_NAMES = {"en": "English", "es": "Español", "fr": "Français", "de": "Deutsch",
              "zh": "中文", "ja": "日本語", "pt": "Português"}


def status_rows() -> list[dict]:
    """The `## Certifications` table of docs/STATUS.md, as dicts."""
    text = STATUS.read_text(encoding="utf-8")
    section = text.split("## Certifications", 1)[1].split("\n## ", 1)[0]
    lines = [l for l in section.splitlines() if l.startswith("|")]
    header = [c.strip() for c in lines[0].strip("|").split("|")]
    rows = []
    for line in lines[2:]:
        cells = [c.strip() for c in line.strip("|").split("|")]
        rows.append(dict(zip(header, cells)))
    return rows


def table() -> str:
    catalog = yaml.safe_load(CATALOG.read_text(encoding="utf-8"))["certs"]
    ready, coming = [], []
    for row in status_rows():
        cert = row["Cert"].strip("`")
        entry = catalog.get(cert, {})
        langs = [code for code in LANG_NAMES if row.get(code.upper()) == "✅"]
        name = entry.get("name", cert)
        label = f"{name} (`{cert}`)"
        vendor = entry.get("vendor", "")
        if langs:
            ready.append(f"| {label} | {vendor} | {row['Topics']} | "
                         f"{', '.join(LANG_NAMES[c] for c in langs)} |")
        elif row["Topics"] not in ("–", "0"):
            coming.append(f"`{cert}`")
    out = [f"**{len(ready)} certifications ready to study**, "
           f"{len(ready) + len(coming)} with a frozen syllabus.", "",
           "| Certification | Vendor | Topics | Complete in |", "|---|---|---|---|", *ready]
    if coming:
        out += ["", "Syllabus frozen, material not written yet: " + ", ".join(coming) + "."]
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true",
                        help="exit non-zero if the block is out of date")
    args = parser.parse_args()
    text = DOC.read_text(encoding="utf-8")
    if START not in text or END not in text:
        print(f"Markers {START} / {END} not found in README.md.")
        return 1
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    block = (f"{START}\n<!-- Generated by scripts/gen_readme_table.py from docs/STATUS.md. "
             f"Do not edit by hand. -->\n\n{table()}\n\n{END}")
    updated = head + block + tail
    if args.check:
        if updated != text:
            print("README.md certification table is stale — run scripts/gen_readme_table.py")
            return 1
        print("README.md certification table matches docs/STATUS.md.")
        return 0
    if updated == text:
        print("README.md already current.")
        return 0
    DOC.write_text(updated, encoding="utf-8")
    print("README.md certification table rewritten.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
