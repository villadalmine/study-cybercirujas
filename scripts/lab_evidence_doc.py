#!/usr/bin/env python3
"""Generate docs/LAB-EVIDENCE.md from the data: deploy/lab-targets.yaml, deploy/lab-evidence.yaml, deploy/killercoda/tracks.yaml.

    python scripts/lab_evidence_doc.py            write the file
    python scripts/lab_evidence_doc.py --check    exit 1 if the file is not what the data generates (CI)
    python scripts/lab_evidence_doc.py --hash cka/1.1   print the lab_hash an evidence entry must carry

The doc is never edited by hand: change the data, run this. It shows, per lab, on which target it was proven
(a check mark), whether the proof is for the lab as it is now (stale = the lab changed since), and why a lab is
not on Killercoda.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from teach.lab import cli, kc_meta, kc_scope, spec  # noqa: E402
from teach.lab import export_killercoda as kc  # noqa: E402

OUT = ROOT / "docs" / "LAB-EVIDENCE.md"
KD = ROOT / "deploy" / "killercoda"

HEAD = """---
title: Lab evidence, per target
generated: true
source: scripts/lab_evidence_doc.py
---
# Lab evidence, per target

*Generated by `scripts/lab_evidence_doc.py` from `deploy/lab-targets.yaml`, `deploy/lab-evidence.yaml` and
`deploy/killercoda/tracks.yaml`. Do not edit by hand: change the data and run `make lab-evidence-doc`;
CI runs it with `--check`.*

A lab is agnostic: it never knows where it runs. Each proof says **where** it ran. A blank cell means "not tested
there", never "does not work". Only a proof on a target that allows publishing (`killercoda-*`, `human-killercoda`)
lets a scenario reach the Killercoda mirror (`study-cybercirujas-killercoda`); an untested lab stays in the repo as
*loaded, not tested*, runs locally with `study-lab`, and is never a CI failure.

## The targets

"""


def _targets_table(targets: dict) -> str:
    rows = ["| Target | Environment | Pinned | Who runs it | A pass proves | A pass does NOT prove | Allows the Killercoda mirror |",
            "| :--- | :--- | :--- | :--- | :--- | :--- | :---: |"]
    for tid, d in targets.items():
        rows.append(f"| `{tid}` | {d['environment']} | {d['pinned']} | {d['runner_kind']} | {d['proves']} | {d['not_proves']} | "
                    f"{'yes' if d['publishes_to_killercoda'] else 'no'} |")
    fields = ", ".join(f"`{f}`" for f in kc_scope.FIELDS)
    return "\n".join(rows) + (f"\n\nEvery proof records {fields}: the date, the sha256 of the lab folder, a run link or a log "
                              "sha256, and what ran it with its version. Proofs live in `deploy/lab-evidence.yaml`.\n")


def _labs(scope: kc_scope.Scope) -> list[spec.Lab]:
    labs = []
    for d in sorted(ROOT.glob("certs/*/*/lab"), key=lambda p: (p.parts[-3], kc.natural(p.parts[-2]))):
        lid = f"{d.parts[-3]}/{d.parts[-2]}"
        if d.parts[-3] in scope.certs or lid in scope.evidence:
            labs.append(spec.load(d, "curated"))
    return labs


def render() -> str:
    scope = kc_scope.load(KD / "tracks.yaml")
    targets = kc_scope.load_targets()
    provable = {f"{c}/{t}" for c, t in cli.provable_labs(KD, scope)}
    labs = _labs(scope)
    cols = list(targets)
    out = [HEAD + _targets_table(targets), "\n## Labs\n"]
    tested = [x for x in (f"{lab.spec['cert']}/{lab.spec['topic']}" for lab in labs) if scope.tested(x)]
    out.append(f"Scope (certifications Killercoda supports): {', '.join(f'`{c}`' for c in scope.certs)}. "
               f"{len(labs)} labs listed, **{len(tested)} tested** on Killercoda, {len(labs) - len(tested)} loaded-untested. "
               "`ok` = proof for the lab as it is now, `stale` = the lab changed since the proof.\n")
    out.append("| Lab | Status | " + " | ".join(f"`{c}`" for c in cols) + " | Why not tested on Killercoda |")
    out.append("| :--- | :--- | " + " | ".join(":---:" for _ in cols) + " | :--- |")
    for lab in labs:
        lid = f"{lab.spec['cert']}/{lab.spec['topic']}"
        cur = kc_meta.lab_hash(lab)
        cells = []
        for c in cols:
            e = scope.evidence.get(lid, {}).get(c)
            cells.append("" if not e else ("ok" if e["lab_hash"] == cur else "stale"))
        out.append(f"| `{lid}` {lab.spec.get('title', '')} | {kc_scope.status(lid, scope)} | " + " | ".join(cells) +
                   f" | {kc_scope.reason(lid, scope, lid in provable)} |")
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    if argv[:1] == ["--hash"]:
        cert, _, topic = argv[1].partition("/")
        print(kc_meta.lab_hash(spec.load(ROOT / "certs" / cert / topic / "lab", "curated")))
        return 0
    text = render()
    if argv[:1] == ["--check"]:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print("docs/LAB-EVIDENCE.md is out of date: run `make lab-evidence-doc`", file=sys.stderr)
            return 1
        print("docs/LAB-EVIDENCE.md is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
